/**
 * Landing fill and outline (drawn first so treads and steel sit on top).
 *
 * @param {object} ctx
 * @param {object} ld  landing
 */
function planDrawLandingFill(ctx, ld) {
  planEl(ctx, 'rect', {
    class: 'sp-landing', fill: '#f4f4f4',
    x: ld.x0, y: ld.y0, width: ld.x1 - ld.x0, height: ld.y1 - ld.y0,
    'stroke-width': ctx.u * PLAN_OUTLINE_U,
  });
  planExt(ctx, ld.x0, ld.y0); planExt(ctx, ld.x1, ld.y1);
}

/**
 * Tread nosing lines and the flight outline.
 *
 * @param {object} ctx
 * @param {object} f  flight
 */
function planDrawTreads(ctx, f) {
  if (!(f.run > 0)) return;
  // Thin lines across the flight at every tread boundary (k = 1..N-1); the
  // first and last boundaries are the flight outline itself.
  const parts = [];
  for (let k = 1; k < f.treads; k++) {
    const a = planFP(f, k * f.d, 0), b = planFP(f, k * f.d, f.width);
    parts.push('M' + planR(a.x) + ' ' + planR(a.y) + 'L' + planR(b.x) + ' ' + planR(b.y));
  }
  if (parts.length) {
    planEl(ctx, 'path', { class: 'sp-tread', fill: 'none', d: parts.join(''),
      'stroke-width': ctx.u * PLAN_TREAD_U });
  }
  // Flight outline (edge of stair).
  planEl(ctx, 'rect', { class: 'sp-ink', fill: 'none', x: f.x0, y: f.y0,
    width: f.x1 - f.x0, height: f.y1 - f.y0, 'stroke-width': ctx.u * PLAN_OUTLINE_U });
  planExt(ctx, f.x0, f.y0); planExt(ctx, f.x1, f.y1);
}

/**
 * Landing steel: the hatched-oval deck symbol, then the X beams (bold lines
 * ACROSS flight 1's travel, each the full landing width, spread over the
 * landing depth), then the Y beams on top (bold lines ALONG flight 1's
 * travel, each the full landing depth, spread over the landing width).
 * The landing rectangle comes from the layout model, so the "landing width"
 * is the landing's real x-extent in every layout (2 x W + well for U-stairs,
 * W for the others). Queues one "C8x11.2 @ LANDING LEVEL" label per axis
 * that has beams, each with its own leader to a beam of that axis.
 *
 * @param {object} ctx
 * @param {object} ld         landing
 * @param {string} chainSide  side of the main dimension chain ('left' |
 *                            'right'); when the labels share it (L-stairs)
 *                            the Y leader keeps clear of the depth text
 */
function planDrawLandingSteel(ctx, ld, chainSide) {
  const depth = ld.y1 - ld.y0, width = ld.x1 - ld.x0;
  const fs = ctx.fs, g = ctx.g;

  // X beams: y positions, near (flight 1 end) -> far. Y beams: x positions,
  // left -> right. Same edge-inset rule on both axes (planBeamPositions).
  const ys = planBeamPositions(ld.y0, ld.y1, g.nBeamsX);
  const xs = planBeamPositions(ld.x0, ld.x1, g.nBeamsY).sort(function (a, b) { return a - b; });

  // Deck symbol: centre of the largest clear bay between beams / edges.
  const bandY = planWidestGap(ld.y0, ld.y1, ys);
  const bandX = planWidestGap(ld.x0, ld.x1, xs);
  planDrawDeckSymbol(ctx, (bandX.a + bandX.b) / 2, (bandY.a + bandY.b) / 2,
    Math.min(width, depth) * 0.16, bandY.b - bandY.a, bandX.b - bandX.a);

  // The beams themselves: X first, Y on top.
  const sw = ctx.u * PLAN_STEEL_U;
  ys.forEach(function (y) {
    planEl(ctx, 'line', { class: 'sp-steel', fill: 'none', x1: ld.x0, y1: y, x2: ld.x1, y2: y,
      'stroke-width': sw });
  });
  xs.forEach(function (x) {
    planEl(ctx, 'line', { class: 'sp-steel', fill: 'none', x1: x, y1: ld.y0, x2: x, y2: ld.y1,
      'stroke-width': sw });
  });

  // Labels. Each arrow tip lands on its own axis's beam, at least `clear`
  // away from every beam of the other axis, so an X leader and a Y leader
  // never point at the same junction.
  const clear = 1.5 * fs;
  const left = ld.labelCol === 'left';
  if (ys.length) {
    // X: the far beam, near the label side (like the old landing channel label).
    const ay = ys[ys.length - 1];
    const ax = planClearSpot(ld.x0, ld.x1, xs, left ? ld.x0 + width * 0.15 : ld.x1 - width * 0.15, clear);
    planQueueLabel(ctx, PLAN_TEXT.beam.replace('{SECTION}', g.beamXName), ax, ay, ld.labelCol, ay - 2.2 * fs);
  }
  if (xs.length) {
    // Y: the beam nearest the label side, about mid-depth, so its leader
    // arrives square to the beam and below the X label's leader.
    const ax = left ? xs[0] : xs[xs.length - 1];
    // Landing depth text sits mid-depth in the chain (planDimV): keep clear.
    const avoid = [];
    if (chainSide === ld.labelCol) {
      const half = planTextW(planFmtFtIn(depth), fs, true) / 2 + 0.8 * fs, mid = ld.y0 + depth / 2;
      avoid.push([mid - half, mid + half]);
    }
    const ay = planClearSpot(ld.y0, ld.y1, ys, ld.y0 + depth * 0.55, 0.8 * clear, avoid);
    planQueueLabel(ctx, PLAN_TEXT.beam.replace('{SECTION}', g.beamYName), ax, ay, ld.labelCol, ay + 0.8 * fs);
  }
}

/**
 * Positions of `n` landing beams spread over one axis of the landing, lo..hi
 * (the same rule for X beams over the depth and Y beams over the width):
 *   1 beam   in the middle,
 *   2+       first and last PLAN_BEAM_EDGE_INSET in from the two edges
 *            (never more than a quarter of the span), the rest evenly between
 *            (so 2 frame the edges, 3 = both edges + the middle).
 * Listed from `hi` towards `lo` (for X beams: near edge -> far edge).
 *
 * @param {number} lo
 * @param {number} hi
 * @param {number} n  beam count (0 -> none)
 * @returns {number[]}
 */
function planBeamPositions(lo, hi, n) {
  const span = hi - lo, out = [];
  if (n === 1) out.push(lo + span / 2);
  else if (n >= 2) {
    const ins = Math.min(PLAN_BEAM_EDGE_INSET, span / 4);
    const step = (span - 2 * ins) / (n - 1);
    for (let i = 0; i < n; i++) out.push(hi - ins - i * step);
  }
  return out;
}

/**
 * Widest clear interval of lo..hi between the given cut positions.
 *
 * @param {number} lo
 * @param {number} hi
 * @param {number[]} cuts  beam positions inside lo..hi
 * @returns {{a:number, b:number}}
 */
function planWidestGap(lo, hi, cuts) {
  const stops = [lo].concat(cuts.slice().sort(function (p, q) { return p - q; }), [hi]);
  let best = { a: lo, b: lo };
  for (let i = 0; i + 1 < stops.length; i++) {
    if (stops[i + 1] - stops[i] > best.b - best.a) best = { a: stops[i], b: stops[i + 1] };
  }
  return best;
}

/**
 * A point on lo..hi as close as possible to `pref` while staying at least
 * `clear` away from the edges and from every cut (the other axis's beams),
 * and outside every `avoid` range (e.g. dimension text the leader would cross).
 * When nothing qualifies, the middle of the widest gap between cuts.
 *
 * @param {number} lo
 * @param {number} hi
 * @param {number[]} cuts
 * @param {number} pref
 * @param {number} clear
 * @param {number[][]} [avoid]  extra forbidden [a, b] ranges
 * @returns {number}
 */
function planClearSpot(lo, hi, cuts, pref, clear, avoid) {
  // Forbidden ranges, merged left to right; the gaps between them are allowed.
  const bad = [[-Infinity, lo + clear], [hi - clear, Infinity]]
    .concat(cuts.map(function (c) { return [c - clear, c + clear]; }), avoid || [])
    .sort(function (p, q) { return p[0] - q[0]; });
  let best = null, reach = -Infinity;
  bad.forEach(function (r) {
    if (r[0] > reach && isFinite(reach)) {
      const c = planClamp(pref, reach, r[0]);               // allowed: reach..r[0]
      if (best === null || Math.abs(c - pref) < Math.abs(best - pref)) best = c;
    }
    reach = Math.max(reach, r[1]);
  });
  if (best !== null) return best;
  const w = planWidestGap(lo, hi, cuts);
  return (w.a + w.b) / 2;
}

/**
 * Hatched oval = "landing deck" symbol from the reference drawings.
 * Drawn in a rotated group; hatch lines are computed chords (no <pattern>, so
 * no ids that could clash when several plans share one page).
 *
 * @param {object} ctx
 * @param {number} cx, cy  centre (in)
 * @param {number} rx      requested half-length (in)
 * @param {number} bandH   height of the clear bay it must fit in (in)
 * @param {number} bandW   width of the clear bay it must fit in (in)
 */
function planDrawDeckSymbol(ctx, cx, cy, rx, bandH, bandW) {
  const ANGLE = -35, RATIO = 0.42;                       // tilt (deg), ry / rx
  const rad = ANGLE * Math.PI / 180;
  // Shrink until the tilted oval's half-extents fit in 40% of the bay.
  let r = planClamp(rx, ctx.fs * 0.6, ctx.fs * 4);
  const halfH = function (q) { return Math.hypot(q * Math.sin(rad), q * RATIO * Math.cos(rad)); };
  const halfW = function (q) { return Math.hypot(q * Math.cos(rad), q * RATIO * Math.sin(rad)); };
  if (halfH(r) > bandH * 0.4) r = bandH * 0.4 / halfH(1);
  if (halfW(r) > bandW * 0.4) r = bandW * 0.4 / halfW(1);
  if (!(r > 0.3)) return;
  const ry = r * RATIO;
  const grp = planEl(ctx, 'g', { transform: 'translate(' + planR(cx) + ' ' + planR(cy) + ') rotate(' + ANGLE + ')' });
  planEl(ctx, 'ellipse', { class: 'sp-deck', fill: '#ffffff', cx: 0, cy: 0, rx: r, ry: ry,
    'stroke-width': ctx.u * PLAN_OUTLINE_U }, null, grp);
  // Hatch: chords across the short axis at even spacing.
  const parts = [];
  const step = r / 5;
  for (let x = -r + step; x < r - step * 0.5; x += step) {
    const h = ry * Math.sqrt(Math.max(0, 1 - (x * x) / (r * r)));
    parts.push('M' + planR(x) + ' ' + planR(-h) + 'L' + planR(x) + ' ' + planR(h));
  }
  planEl(ctx, 'path', { class: 'sp-hatch', fill: 'none', d: parts.join(''),
    'stroke-width': ctx.u * PLAN_TREAD_U }, null, grp);
}

/**
 * Stringers on one flight: two outer CRANKED stringers with a jog where they
 * run into the landing, plus inner stringers when nStringers > 2.
 * Queues one label per member type.
 *
 * @param {object} ctx
 * @param {object} f  flight
 */
function planDrawStringers(ctx, f) {
  if (!(f.run > 0)) return;
  const sw = ctx.u * PLAN_STEEL_U;
  const pos = planStringerPositions(ctx, f);
  // Crank jog length, never more than a quarter of the landing depth.
  const jogLen = ctx.g.L > 0 ? Math.min(PLAN_JOG_LENGTH, ctx.g.L / 4) : 0;

  // Outer stringers: straight along the flight, then a short dog-leg into
  // the landing, stepping towards the middle of the flight.
  pos.outer.forEach(function (t) {
    const inward = t < f.width / 2 ? 1 : -1;
    const tj = t + inward * Math.min(PLAN_JOG_OFFSET, f.width / 8);
    let pts;
    if (f.landingAt === 'end') {
      pts = [planFP(f, 0, t), planFP(f, f.run, t)];
      if (jogLen > 0) pts.push(planFP(f, f.run + jogLen, tj));
    } else {
      pts = [planFP(f, f.run, t), planFP(f, 0, t)];
      if (jogLen > 0) pts.push(planFP(f, -jogLen, tj));
    }
    planPolyline(ctx, pts, 'sp-steel', sw);
  });

  // Inner stringers: plain, full run.
  pos.inner.forEach(function (t) {
    planPolyline(ctx, [planFP(f, 0, t), planFP(f, f.run, t)], 'sp-steel', sw);
  });

  planQueueStringerLabels(ctx, f, pos);
}

/**
 * Queue the CRANKED STRINGER label (and STRINGER for inner ones) for a flight.
 * Anchors are chosen beyond the flight's dimension text so leaders cross the
 * dimension line where it is clear.
 *
 * @param {object} ctx
 * @param {object} f
 * @param {{outer:number[], inner:number[]}} pos
 */
function planQueueStringerLabels(ctx, f, pos) {
  const fs = ctx.fs;
  const g = ctx.g;
  const vertical = planIsVertical(f);
  const tOuter = f.labelEdge === 'min' ? pos.outer[0] : pos.outer[1];
  const tInner = pos.inner.length ? (f.labelEdge === 'min' ? pos.inner[0] : pos.inner[pos.inner.length - 1]) : null;

  // Half the length of the run dimension's text, so anchors avoid it.
  const half = Math.max(planTextW(planTreadText(f), fs, true), planTextW(planFmtFtIn(f.run), fs, true)) / 2 + 0.8 * fs;
  let sCr, sIn;
  if (vertical) {
    sCr = planClamp(f.run / 2 + half, f.run * 0.55, f.run * 0.93);
    sIn = planClamp(f.run / 2 - half, f.run * 0.07, f.run * 0.45);
  } else {
    // Horizontal flights are labelled from beyond their far end.
    sCr = f.run * 0.8;
    sIn = f.run * 0.9;
  }

  // Which way +s goes in y (for vertical flights), so labels sit on the side
  // of the anchor away from the dimension text.
  const sy = f.dir === 'up' ? -1 : 1;

  // Short flight: its dimension text spills past the far end of the flight
  // (see planDrawDimensions), so aim both labels from the landing side instead.
  let crDir = 1, inDir = -1;                                // +1 = towards +s
  if (vertical && 2 * half > f.run) {
    sCr = f.run * 0.6; sIn = f.run * 0.4;
    crDir = inDir = f.landingAt === 'end' ? 1 : -1;
  }

  const pc = planFP(f, sCr, tOuter);
  planQueueLabel(ctx, PLAN_TEXT.cranked.replace('{SECTION}', g.stringerName), pc.x, pc.y, f.labelCol,
    vertical ? pc.y + sy * crDir * 1.8 * fs : pc.y - 2.6 * fs);

  if (tInner !== null) {
    const pi = planFP(f, sIn, tInner);
    planQueueLabel(ctx, PLAN_TEXT.inner.replace('{SECTION}', g.stringerName), pi.x, pi.y, f.labelCol,
      vertical ? pi.y + sy * inDir * 1.8 * fs : pi.y - 0.8 * fs);
  }
}

/**
 * "UP" arrow on a flight: text near the start, arrow pointing in the
 * direction of travel. With inner stringers it runs in the bay between the
 * labelled-side outer stringer and the inner pair (as in the drawings).
 *
 * @param {object} ctx
 * @param {object} f
 */
function planDrawUpArrow(ctx, f) {
  if (!(f.run > 0)) return;
  const fs = ctx.fs;
  const pos = planStringerPositions(ctx, f);
  // Lane across the flight.
  let lane = f.width / 2;
  if (pos.inner.length) lane = (pos.outer[0] + pos.inner[0]) / 2;

  // Along the flight: "UP" text, then the arrow up to 85% of the run.
  const textS = f.run * 0.06 + 0.7 * fs;
  let a0 = textS + (planIsVertical(f) ? 0.9 : 1.2) * fs;
  let a1 = Math.max(a0 + 1.5 * fs, f.run * 0.85);
  const showText = a1 <= f.run * 0.95;
  if (!showText) { a0 = f.run * 0.15; a1 = f.run * 0.85; }  // too short: arrow only

  const p0 = planFP(f, a0, lane), p1 = planFP(f, a1, lane);
  const hl = Math.min(PLAN_ARROW_LEN * fs, (a1 - a0) * 0.4);
  const pb = planFP(f, a1 - hl, lane);
  planEl(ctx, 'line', { class: 'sp-ink', fill: 'none', x1: p0.x, y1: p0.y, x2: pb.x, y2: pb.y,
    'stroke-width': ctx.u * PLAN_OUTLINE_U });
  planArrowHead(ctx, p1.x, p1.y, p0.x, p0.y, hl, hl * 0.32);

  if (showText) {
    const pt = planFP(f, textS, lane);
    planText(ctx, pt.x, pt.y + 0.35 * fs, PLAN_TEXT.up, fs, 'middle', {});
  }
}

