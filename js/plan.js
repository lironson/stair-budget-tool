/**
 * Read `state` into a clean geometry object `g`, clamping every number so the
 * layout can trust it. Missing values fall back to the contract defaults.
 *
 * @param {object} state
 * @returns {object} g  { orientation, treads1, treads2, d, W, L, G, nStringers,
 *                        nBeamsX, nBeamsY, nLandings, stringerName, beamXName,
 *                        beamYName, hasFlight2, run1, run2 }
 */
function planReadState(state) {
  const orientation = planNormalizeOrientation(state.orientation);
  const g = {
    orientation: orientation,
    treads1: Math.round(planNum(state.treads1, 10, 0, PLAN_MAX_TREADS)),
    treads2: Math.round(planNum(state.treads2, 10, 0, PLAN_MAX_TREADS)),
    d: planNum(state.treadDepth, 11, PLAN_MIN_TREAD_DEPTH, PLAN_MAX_TREAD_DEPTH),
    W: planNum(state.stairWidth, 44, PLAN_MIN_WIDTH, PLAN_MAX_WIDTH),
    L: planNum(state.landingDepth, 48, 0, PLAN_MAX_LANDING),
    G: planNum(state.wellGap, 4, 0, PLAN_MAX_WELL),
    // 2 = outer pair only, 3 = one inner at the centre, 4 = two inner.
    nStringers: Math.round(planNum(state.stringersPerFlight, 2, 2, 4)),
    // Landing beams per landing: X = across flight 1's travel, Y = along it.
    nBeamsX: Math.round(planNum(state.beamXCount, 2, 0, PLAN_MAX_BEAMS)),
    nBeamsY: Math.round(planNum(state.beamYCount, 2, 0, PLAN_MAX_BEAMS)),
    // Landings priced; 2+ turns on the upper landing view (renderUpperLanding).
    nLandings: Math.round(planNum(state.landingCount, 1, 0, PLAN_MAX_LANDINGS)),
    stringerName: planSectionName(state.stringerSection, state.stringerCustomLbFt, 'C12x20.7'),
    beamXName: planSectionName(state.beamXSection, state.beamXCustomLbFt, 'C8x11.2'),
    beamYName: planSectionName(state.beamYSection, state.beamYCustomLbFt, 'C8x11.2'),
  };
  g.hasFlight2 = orientation !== 'straight';
  if (!g.hasFlight2) g.treads2 = 0;
  g.run1 = g.treads1 * g.d;                 // horizontal run of flight 1
  g.run2 = g.treads2 * g.d;                 // horizontal run of flight 2
  return g;
}

/**
 * Orientation as one of PLAN_ORIENTATIONS. Uses normalizeOrientation() from
 * calc.js when it is loaded; otherwise (or if it returns something this file
 * cannot draw) a local copy of the same mapping:
 *   'straight' / 'inline' / 'L' / 'U'  unchanged,
 *   'L-left' / 'L-right' (old saves)   -> 'L',
 *   'U-left' / 'U-right' (old saves)   -> 'U',
 *   anything else                      -> 'U'.
 *
 * @param {*} o  state.orientation
 * @returns {string}
 */
function planNormalizeOrientation(o) {
  if (typeof normalizeOrientation === 'function') {
    const n = normalizeOrientation(o);
    if (PLAN_ORIENTATIONS.indexOf(n) >= 0) return n;
  }
  if (PLAN_ORIENTATIONS.indexOf(o) >= 0) return o;
  if (o === 'L-left' || o === 'L-right') return 'L';
  return 'U';
}

/**
 * Text shown for a channel size: the section name, or "CUSTOM 20 LB/FT".
 *
 * @param {string} name       state.*Section
 * @param {number} customLbFt state.*CustomLbFt
 * @param {string} fallback   used when the name is empty
 * @returns {string}
 */
function planSectionName(name, customLbFt, fallback) {
  if (name === 'Custom') {
    return PLAN_TEXT.custom.replace('{LBFT}', String(Math.round(planNum(customLbFt, 0, 0, 9999) * 100) / 100));
  }
  const s = (typeof name === 'string' && name.trim()) ? name.trim() : fallback;
  return s.slice(0, 24);
}

/* =============================================================================
 * Layout (ARCHITECTURE.md §3)
 *
 * A "flight" object:
 *   { num, x0, y0, x1, y1,      bounding rectangle (in)
 *     dir,                      travel direction going UP the stair:
 *                               'up' | 'down' | 'right' (on screen)
 *     run, width, treads, d,
 *     landingAt,                'end' (flight 1, and the upper landing's
 *                               arriving flight) or 'start' (flight 2): which
 *                               end meets the landing, gets the crank jog
 *     labelCol,                 'left' | 'right' label column for its labels
 *     labelEdge,                'min' | 'max': which outer stringer is labelled
 *                               (min = the x0 / y0 side)
 *     dimSide }                 'chain' (in the main vertical string with the
 *                               landing), 'right' (U) or 'top' (L)
 * The model:
 *   { flights: [f1, f2?], landing: {x0,y0,x1,y1,labelCol} | null,
 *     chainSide: 'left' | 'right' }
 * (planLayoutUpper returns its own variant, documented there.)
 * ========================================================================== */

/**
 * Pick the layout function for g.orientation.
 *
 * @param {object} g  from planReadState
 * @returns {object} model
 */
function planLayout(g) {
  switch (g.orientation) {
    case 'straight': return planLayoutStraight(g);
    case 'inline': return planLayoutInline(g);
    case 'L': return planLayoutL(g);
    default: return planLayoutU(g);
  }
}

/**
 * Build a flight record. (x0, y0) is the top-left corner of its rectangle;
 * vertical flights are `width` wide and `run` tall, horizontal ones the
 * other way round.
 *
 * @param {number} num        1 or 2
 * @param {number} x0         left edge (in)
 * @param {number} y0         top edge (in)
 * @param {string} dir        'up' | 'down' | 'right'
 * @param {number} treads
 * @param {object} g
 * @param {object} extra      labelCol, labelEdge, dimSide, landingAt
 * @returns {object} flight
 */
function planMakeFlight(num, x0, y0, dir, treads, g, extra) {
  const run = treads * g.d;
  const vertical = dir === 'up' || dir === 'down';
  const f = {
    num: num, x0: x0, y0: y0,
    x1: x0 + (vertical ? g.W : run),
    y1: y0 + (vertical ? run : g.W),
    dir: dir, run: run, width: g.W, treads: treads, d: g.d,
  };
  for (const k in extra) f[k] = extra[k];
  return f;
}

/**
 * 'straight': flight 1 going up, landing on top (landingDepth x stairWidth).
 * Labels on the left, dimensions on the right.
 *
 * @param {object} g
 * @returns {object} model
 */
function planLayoutStraight(g) {
  // Flight 1 occupies x 0..W, y -run1..0.
  const f1 = planMakeFlight(1, 0, -g.run1, 'up', g.treads1, g,
    { landingAt: 'end', labelCol: 'left', labelEdge: 'min', dimSide: 'chain' });
  // Landing sits directly above flight 1.
  const landing = planMakeLanding(0, -g.run1 - g.L, g.W, g.L, 'left');
  return { flights: [f1], landing: landing, chainSide: 'right' };
}

/**
 * 'inline': flight 1, the landing, then flight 2 carrying straight on up.
 * Labels on the left, one dimension chain (run 1 / landing / run 2) on the right.
 *
 * @param {object} g
 * @returns {object} model
 */
function planLayoutInline(g) {
  const f1 = planMakeFlight(1, 0, -g.run1, 'up', g.treads1, g,
    { landingAt: 'end', labelCol: 'left', labelEdge: 'min', dimSide: 'chain' });
  const landing = planMakeLanding(0, -g.run1 - g.L, g.W, g.L, 'left');
  // Flight 2 starts at the top edge of the landing and keeps going up.
  const f2 = planMakeFlight(2, 0, -g.run1 - g.L - g.run2, 'up', g.treads2, g,
    { landingAt: 'start', labelCol: 'left', labelEdge: 'min', dimSide: 'chain' });
  return { flights: [f1, f2], landing: landing, chainSide: 'right' };
}

/**
 * 'L': flight 1 up to a landingDepth x stairWidth landing; flight 2 leaves the
 * landing's right side turned 90 degrees, flush with the far (top) edge of
 * the landing.
 * Flight 1 and the landing are labelled and dimensioned on the left, away
 * from flight 2; flight 2 is labelled from the column beyond its far (right)
 * end and dimensioned above.
 *
 * @param {object} g
 * @returns {object} model
 */
function planLayoutL(g) {
  const f1 = planMakeFlight(1, 0, -g.run1, 'up', g.treads1, g,
    { landingAt: 'end', labelCol: 'left', labelEdge: 'min', dimSide: 'chain' });
  const yTop = -g.run1 - g.L;                            // far edge of the landing
  const landing = planMakeLanding(0, yTop, g.W, g.L, 'left');
  // Flight 2: top edge flush with the landing's far edge, running right.
  const f2 = planMakeFlight(2, g.W, yTop, 'right', g.treads2, g,
    { landingAt: 'start', labelCol: 'right', labelEdge: 'min', dimSide: 'top' });
  return { flights: [f1, f2], landing: landing, chainSide: 'left' };
}

/**
 * 'U': flight 1 up to a full-width landing (2 x stairWidth + wellGap),
 * flight 2 comes back down beside flight 1 on the right, with wellGap between
 * the two flights.
 * Each flight is labelled and dimensioned on its own outside face (flight 1
 * left, flight 2 right); the landing label goes on flight 2's side (right) to
 * balance the two label columns.
 *
 * @param {object} g
 * @returns {object} model
 */
function planLayoutU(g) {
  const f1 = planMakeFlight(1, 0, -g.run1, 'up', g.treads1, g,
    { landingAt: 'end', labelCol: 'left', labelEdge: 'min', dimSide: 'chain' });
  // Landing spans both flights and the well between them.
  const landing = planMakeLanding(0, -g.run1 - g.L, 2 * g.W + g.G, g.L, 'right');
  // Flight 2 starts at the landing's near edge (y = -run1) and travels down.
  const f2 = planMakeFlight(2, g.W + g.G, -g.run1, 'down', g.treads2, g,
    { landingAt: 'start', labelCol: 'right', labelEdge: 'max', dimSide: 'right' });
  return { flights: [f1, f2], landing: landing, chainSide: 'left' };
}

/**
 * Upper landing view (drawing 2, ARCHITECTURE.md §3 "Upper landing"): the
 * landing at the top of the last flight, the same size as landing 1
 * (landingWidth x landingDepth, in the same plan directions), and the last
 * PLAN_UPPER_TREADS treads of the arriving flight as a "stub" cut off with a
 * break line at its free (lower) end.
 *   straight / inline  stub going up, landing above it.
 *   L                  stub (flight 2) running right, landing beyond its right
 *                      end; the stub meets the landing's left edge, flush
 *                      with its far (top) edge.
 *   U                  stub (flight 2) running down on the right, landing
 *                      below it across the full width; the stub meets the
 *                      right half of the landing's top edge.
 * The stub is a normal flight record (see above) whose run also includes a
 * short cut-off `tail` before its first shown nosing; s = 0 is the break line.
 *
 * @param {object} g   from planReadState
 * @param {number} fs  font size (in), for the length of the cut-off tail
 * @returns {object} { flights: [stub] or [] (arriving flight has 0 treads),
 *                     landing: {x0,y0,x1,y1,labelCol} | null,
 *                     arriving: { num, treads, d } (the whole arriving flight),
 *                     widthSide: 'top' | 'bottom', depthSide: 'left' | 'right' }
 */
function planLayoutUpper(g, fs) {
  const num = g.orientation === 'straight' ? 1 : 2;
  const n = num === 1 ? g.treads1 : g.treads2;
  const k = Math.min(PLAN_UPPER_TREADS, n);                // treads shown
  const tail = k > 0 ? Math.max(PLAN_UPPER_TAIL_D * g.d, PLAN_UPPER_TAIL_FS * fs) : 0;
  const run = k * g.d + tail;                              // stub length incl. tail
  const arriving = { num: num, treads: n, d: g.d };
  let stub = null, landing, widthSide, depthSide;

  if (g.orientation === 'L') {
    // Stub x 0..run, y 0..W; landing to its right, top edges flush.
    landing = planMakeLanding(run, 0, g.W, g.L, 'right');
    if (k > 0) stub = planMakeStub(num, 0, 0, 'right', k, tail, g, { labelCol: 'left', labelEdge: 'min' });
    widthSide = 'top'; depthSide = 'right';
  } else if (g.orientation === 'U') {
    // Stub on the right half, y 0..run; full-width landing below it.
    landing = planMakeLanding(0, run, 2 * g.W + g.G, g.L, 'left');
    if (k > 0) stub = planMakeStub(num, g.W + g.G, 0, 'down', k, tail, g, { labelCol: 'right', labelEdge: 'max' });
    widthSide = 'bottom'; depthSide = 'left';
  } else {
    // straight / inline: stub x 0..W, y -run..0 going up; landing above it.
    landing = planMakeLanding(0, -run - g.L, g.W, g.L, 'left');
    if (k > 0) stub = planMakeStub(num, 0, -run, 'up', k, tail, g, { labelCol: 'left', labelEdge: 'min' });
    widthSide = 'top'; depthSide = 'right';
  }
  return { flights: stub ? [stub] : [], landing: landing, arriving: arriving,
    widthSide: widthSide, depthSide: depthSide };
}

/**
 * The arriving flight's stub for the upper landing view: a flight record of
 * `k` treads whose run (and rectangle) also includes the cut-off `tail`
 * before the first shown nosing. Its top end meets the landing
 * (landingAt 'end'), so the outer stringers get the crank jog there.
 *
 * @param {number} num     arriving flight number (1 or 2)
 * @param {number} x0      left edge (in)
 * @param {number} y0      top edge (in)
 * @param {string} dir     'up' | 'down' | 'right'
 * @param {number} k       treads shown
 * @param {number} tail    cut-off length (in)
 * @param {object} g
 * @param {object} extra   labelCol, labelEdge
 * @returns {object} flight (with .tail)
 */
function planMakeStub(num, x0, y0, dir, k, tail, g, extra) {
  const f = planMakeFlight(num, x0, y0, dir, k, g, extra);
  f.run = k * g.d + tail;
  f.tail = tail;
  f.landingAt = 'end';
  f.dimSide = 'none';
  if (planIsVertical(f)) f.y1 = y0 + f.run; else f.x1 = x0 + f.run;
  return f;
}

/**
 * Build a landing record, or null when the landing depth is 0.
 *
 * @param {number} x0        left edge (in)
 * @param {number} y0        top (far) edge (in)
 * @param {number} width     across flight 1's travel (in)
 * @param {number} depth     along flight 1's travel (in)
 * @param {string} labelCol  'left' | 'right' column for its beam labels
 * @returns {object|null}
 */
function planMakeLanding(x0, y0, width, depth, labelCol) {
  if (!(depth > 0.01)) return null;
  return { x0: x0, y0: y0, x1: x0 + width, y1: y0 + depth, labelCol: labelCol };
}

/**
 * Bounding box of the stair (flights + landing), ignoring annotation.
 *
 * @param {object} model
 * @param {object} g
 * @returns {{x0:number,y0:number,x1:number,y1:number}}
 */
function planGeomBounds(model, g) {
  const b = { x0: 0, y0: 0, x1: g.W, y1: 0 };           // always include flight 1's foot
  const rects = model.flights.filter(function (f) { return f.run > 0; });
  if (model.landing) rects.push(model.landing);
  rects.forEach(function (r) {
    b.x0 = Math.min(b.x0, r.x0); b.y0 = Math.min(b.y0, r.y0);
    b.x1 = Math.max(b.x1, r.x1); b.y1 = Math.max(b.y1, r.y1);
  });
  return b;
}

