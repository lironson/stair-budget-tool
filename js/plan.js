/**
 * All dimension strings:
 *   - the main vertical chain on model.chainSide: flight 1 run, landing depth
 *     (and flight 2 run for 'inline'),
 *   - flight 2's run on its right side ('U') or above it ('L'),
 *   - the width string under the stair (U-stairs: W | well | W).
 *
 * @param {object} ctx
 * @param {object} model
 * @param {object} gb  stair bounds
 */
function planDrawDimensions(ctx, model, gb) {
  const fs = ctx.fs, off = PLAN_DIM_OFFSET * fs;
  const f1 = model.flights[0];
  const ld = model.landing;

  // --- main vertical chain beside flight 1 and the landing ---------------
  const side = model.chainSide;
  const xEdge = side === 'left' ? f1.x0 : f1.x1;
  const xLine = side === 'left' ? Math.min(gb.x0, xEdge) - off : Math.max(gb.x1, xEdge) + off;
  const chain = [];
  model.flights.forEach(function (f) {
    if (f.dimSide === 'chain' && f.run > 0) chain.push({ a: f.y0, b: f.y1, f: f });
  });
  if (ld) chain.push({ a: ld.y0, b: ld.y1, f: null });
  chain.forEach(function (c) {
    const texts = c.f ? [planFmtFtIn(c.f.run), planTreadText(c.f)] : [planFmtFtIn(c.b - c.a)];
    // Text too long for a short flight spills past the flight's free end:
    // below flight 1's foot, above the top of an inline flight 2.
    const spill = !c.f ? null : c.f.num === 1 ? 'b' : 'a';
    planDimV(ctx, xLine, c.a, c.b, xEdge, side, texts, spill);
  });

  // --- flight 2 on its own ---------------------------------------------------
  model.flights.forEach(function (f) {
    if (!(f.run > 0) || f.dimSide === 'chain') return;
    const texts = [planFmtFtIn(f.run), planTreadText(f)];
    if (f.dimSide === 'top') {
      // L-stair: spill past the far (right) end of flight 2.
      planDimH(ctx, f.y0 - off, f.x0, f.x1, f.y0, f.y0, 'top', texts, 'b');
    } else {
      // U-stair: on flight 2's right side, spilling below its foot.
      planDimV(ctx, f.x1 + off, f.y0, f.y1, f.x1, 'right', texts, 'b');
    }
  });

  // --- width string under the stair -------------------------------------------
  // Flights whose foot is on the bottom of the drawing: flight 1, and the
  // returning flight of a U-stair. Sorted left to right, wells in between.
  // (A flight with 0 treads is skipped; with no flights at all the landing
  // width is dimensioned instead.)
  let feet = model.flights.filter(function (f) { return f.run > 0 && (f.num === 1 || f.dir === 'down'); })
    .sort(function (a, b) { return a.x0 - b.x0; });
  if (!feet.length && ld) feet = [{ x0: ld.x0, x1: ld.x1, y1: ld.y1, width: ld.x1 - ld.x0 }];
  const yLine = gb.y1 + off;
  const segs = [];
  feet.forEach(function (f, i) {
    segs.push([f.x0, f.x1, f.y1, f.y1]);
    const next = feet[i + 1];
    if (next && next.x0 - f.x1 > 0.01) segs.push([f.x1, next.x0, f.y1, next.y1]);
  });
  // Texts too long for their segment go on a row below the line; on a narrow
  // U-stair (W | well | W) a text that would run into the previous one on
  // that row drops to the next row down.
  const rowEnd = [];                                          // right end of the last text per row
  segs.forEach(function (sg) {
    const str = planFmtFtIn(sg[1] - sg[0]);
    const tw = planTextW(str, fs, true), mid = (sg[0] + sg[1]) / 2;
    let row = 1;
    if (tw > sg[1] - sg[0] - 0.8 * fs) {
      while (rowEnd[row] !== undefined && rowEnd[row] > mid - tw / 2 - 0.5 * fs) row++;
      rowEnd[row] = mid + tw / 2;
    }
    planDimH(ctx, yLine, sg[0], sg[1], sg[2], sg[3], 'bottom', [str], undefined, row);
  });
}

/**
 * Vertical dimension with extension lines, 45-degree ticks and rotated text.
 * texts[0] goes outside the line, texts[1] (if any) inside, between the line
 * and the stair. Text that does not fit between the ticks moves further out.
 *
 * @param {object} ctx
 * @param {number} x      dimension line x
 * @param {number} yA     top end (in)
 * @param {number} yB     bottom end (in)
 * @param {number} xEdge  x of the object edge the extension lines start from
 * @param {string} side   'left' | 'right': side of the object the dim is on
 * @param {string[]} texts
 * @param {string} [spill]  'a' (top) or 'b' (bottom): when the text does not
 *                          fit, slide it past that end instead of stacking it
 *                          further out. Omit to stack.
 */
function planDimV(ctx, x, yA, yB, xEdge, side, texts, spill) {
  if (!(yB - yA > 0.01)) return;
  const fs = ctx.fs, out = side === 'left' ? -1 : 1;
  const w = ctx.u * PLAN_DIM_U;
  const gap = ctx.u * 0.6, over = fs * 0.4;
  // Extension lines from just off the object to just past the dimension line.
  [yA, yB].forEach(function (y) {
    planLine(ctx, xEdge + out * gap, y, x + out * over, y, 'sp-dim', w);
  });
  planLine(ctx, x, yA, x, yB, 'sp-dim', w);                  // dimension line
  planTick(ctx, x, yA); planTick(ctx, x, yB);                // end ticks

  // Text: rotated -90 (reads bottom to top); glyph "up" points to -x.
  const len = yB - yA, mid = (yA + yB) / 2;
  const tg = 0.3 * fs, capH = PLAN_CAP_H * fs, lh = PLAN_TEXT_LINE * fs;
  let slot = 0;                                              // next free outside line
  texts.forEach(function (str, i) {
    const tw = planTextW(str, fs, true);
    const fits = tw <= len - 0.8 * fs;
    let bx, cy = mid;
    if (!fits && spill) {
      // Slide along the line past the free end, keeping its own side.
      cy = spill === 'a' ? yA - 0.6 * fs - tw / 2 : yB + 0.6 * fs + tw / 2;
      bx = i === 1 ? (out < 0 ? x + tg + capH : x - tg) : (out < 0 ? x - tg : x + tg + capH);
    } else if (i === 1 && fits) {
      // Inside: between dimension line and stair.
      bx = out < 0 ? x + tg + capH : x - tg;
    } else {
      if (!fits && slot === 0) slot = 1;                     // keep slot 0 for texts that fit
      bx = out < 0 ? x - tg - slot * lh : x + tg + capH + slot * lh;
      slot++;
    }
    planText(ctx, bx, cy, str, fs, 'middle', { rotate: true, dim: true });
  });
}

/**
 * Horizontal dimension, same rules as planDimV.
 *
 * @param {object} ctx
 * @param {number} y       dimension line y
 * @param {number} xA      left end (in)
 * @param {number} xB      right end (in)
 * @param {number} yEdgeA  object edge y at the left end
 * @param {number} yEdgeB  object edge y at the right end
 * @param {string} side    'top' | 'bottom'
 * @param {string[]} texts texts[0] outside, texts[1] inside
 * @param {string} [spill]  'a' (left) or 'b' (right), as in planDimV
 * @param {number} [row]    first outside row for text that does not fit
 *                          between the ticks (default 1, the row past the
 *                          one fitting text uses)
 */
function planDimH(ctx, y, xA, xB, yEdgeA, yEdgeB, side, texts, spill, row) {
  if (!(xB - xA > 0.01)) return;
  const fs = ctx.fs, out = side === 'top' ? -1 : 1;
  const w = ctx.u * PLAN_DIM_U;
  const gap = ctx.u * 0.6, over = fs * 0.4;
  planLine(ctx, xA, yEdgeA + out * gap, xA, y + out * over, 'sp-dim', w);
  planLine(ctx, xB, yEdgeB + out * gap, xB, y + out * over, 'sp-dim', w);
  planLine(ctx, xA, y, xB, y, 'sp-dim', w);
  planTick(ctx, xA, y); planTick(ctx, xB, y);

  const len = xB - xA, mid = (xA + xB) / 2;
  const tg = 0.3 * fs, capH = PLAN_CAP_H * fs, lh = PLAN_TEXT_LINE * fs;
  let slot = 0;
  texts.forEach(function (str, i) {
    const tw = planTextW(str, fs, true);
    const fits = tw <= len - 0.8 * fs;
    let by;
    if (!fits && spill) {
      const cx = spill === 'a' ? xA - 0.6 * fs - tw / 2 : xB + 0.6 * fs + tw / 2;
      by = i === 1 ? (out < 0 ? y + tg + capH : y - tg) : (out < 0 ? y - tg : y + tg + capH);
      planText(ctx, cx, by, str, fs, 'middle', { dim: true });
      return;
    }
    if (i === 1 && fits) {
      by = out < 0 ? y + tg + capH : y - tg;
    } else {
      if (!fits && slot < (row || 1)) slot = row || 1;
      // Rows past the first are spread a little wider: they hold texts that
      // overlap the row above end to end (narrow U-stair width string).
      const step = slot * lh + Math.max(0, slot - 1) * 0.25 * fs;
      by = out < 0 ? y - tg - step : y + tg + capH + step;
      slot++;
    }
    planText(ctx, mid, by, str, fs, 'middle', { dim: true });
  });
}

/**
 * 45-degree architectural tick at a dimension end.
 *
 * @param {object} ctx
 * @param {number} x
 * @param {number} y
 */
function planTick(ctx, x, y) {
  const h = ctx.fs * 0.32;
  planLine(ctx, x - h, y + h, x + h, y - h, 'sp-dim', ctx.u * PLAN_TICK_U);
}

/**
 * "10 TR @ 11"" text for a flight.
 *
 * @param {object} f
 * @returns {string}
 */
function planTreadText(f) {
  return PLAN_TEXT.treads.replace('{N}', String(f.treads)).replace('{D}', planFmtIn(f.d));
}

/* =============================================================================
 * Upper landing view (drawing 2): flight stub, break line, dimensions, note
 * ========================================================================== */

/**
 * Treads of the arriving flight's stub: a nosing line for each shown tread
 * (the first one `tail` in from the break line), and the stub outline on its
 * two sides and the landing end. The cut end has no outline: the break line
 * (planDrawBreak) goes there.
 *
 * @param {object} ctx
 * @param {object} f  stub (planMakeStub)
 */
function planDrawStubTreads(ctx, f) {
  const parts = [];
  for (let i = 0; i < f.treads; i++) {
    const s = f.tail + i * f.d;
    const a = planFP(f, s, 0), b = planFP(f, s, f.width);
    parts.push('M' + planR(a.x) + ' ' + planR(a.y) + 'L' + planR(b.x) + ' ' + planR(b.y));
  }
  if (parts.length) {
    planEl(ctx, 'path', { class: 'sp-tread', fill: 'none', d: parts.join(''),
      'stroke-width': ctx.u * PLAN_TREAD_U });
  }
  planPolyline(ctx, [planFP(f, 0, 0), planFP(f, f.run, 0), planFP(f, f.run, f.width), planFP(f, 0, f.width)],
    'sp-ink', ctx.u * PLAN_OUTLINE_U);
}

/**
 * Cut end of the stub:
 *   - a break line across the free end (s = 0), running a little past both
 *     flight edges, with one sharp zig-zag in the middle,
 *   - a small break mark on every stringer, halfway along the tail: a
 *     paper-coloured gap in the steel between two short slanted strokes.
 *
 * @param {object} ctx
 * @param {object} f  stub (planMakeStub)
 */
function planDrawBreak(ctx, f) {
  const fs = ctx.fs, W = f.width, w = ctx.u * PLAN_OUTLINE_U;
  const over = PLAN_BREAK_OVER * fs;
  const zh = Math.min(PLAN_BREAK_ZIG * fs, f.tail * 0.45);  // zig height along the flight
  // The zig sits mid-flight, or with inner stringers in the outer bay on the
  // labelled side (clear of the steel and of the UP arrow's bay).
  const pos = planStringerPositions(ctx, f);
  let lo = pos.outer[0], hi = pos.outer[1];
  if (pos.inner.length) {
    if (f.labelEdge === 'min') hi = pos.inner[0]; else lo = pos.inner[pos.inner.length - 1];
  }
  const c = (lo + hi) / 2;
  const zw = Math.min(0.9 * fs, W / 4, (hi - lo) * 0.4);    // zig half-width across it
  planPolyline(ctx, [
    planFP(f, 0, -over), planFP(f, 0, c - zw), planFP(f, zh, c - zw / 3),
    planFP(f, -zh, c + zw / 3), planFP(f, 0, c + zw), planFP(f, 0, W + over),
  ], 'sp-ink', w);

  // Stringer break marks, centred on each stringer halfway along the tail,
  // short enough not to touch the mark on the next stringer.
  const ts = pos.outer.concat(pos.inner).sort(function (a, b) { return a - b; });
  let spacing = Infinity;
  for (let i = 1; i < ts.length; i++) spacing = Math.min(spacing, ts[i] - ts[i - 1]);
  const sm = f.tail / 2;
  const half = Math.min(Math.max(PLAN_BREAK_MARK * fs, ctx.u * PLAN_STEEL_U * 1.2), spacing * 0.4);
  const gap = Math.min(PLAN_BREAK_MARK_GAP * fs, f.tail * 0.3) / 2;
  const slant = half * 0.5;                                 // lean along the flight
  ts.forEach(function (t) {
    const p = function (ds, dt) { return planFP(f, sm + ds, t + dt); };
    const q = [p(-gap - slant, -half), p(-gap + slant, half), p(gap + slant, half), p(gap - slant, -half)];
    planEl(ctx, 'polygon', { class: 'sp-paper', fill: '#ffffff',
      points: q.map(function (v) { return planR(v.x) + ',' + planR(v.y); }).join(' ') });
    planPolyline(ctx, [q[0], q[1]], 'sp-ink', w);
    planPolyline(ctx, [q[3], q[2]], 'sp-ink', w);
  });
}

/**
 * Upper landing dimensions: its width (above it, or below for U-stairs,
 * where the stub sits on top) and its depth (on the side away from the
 * stub). No flight run chain.
 *
 * @param {object} ctx
 * @param {object} model  from planLayoutUpper
 * @param {object} gb     bounds of the landing + stub
 */
function planDrawUpperDimensions(ctx, model, gb) {
  const ld = model.landing;
  if (!ld) return;
  const off = PLAN_DIM_OFFSET * ctx.fs;
  const width = [planFmtFtIn(ld.x1 - ld.x0)], depth = [planFmtFtIn(ld.y1 - ld.y0)];
  if (model.widthSide === 'bottom') {
    planDimH(ctx, Math.max(gb.y1, ld.y1) + off, ld.x0, ld.x1, ld.y1, ld.y1, 'bottom', width);
  } else {
    planDimH(ctx, Math.min(gb.y0, ld.y0) - off, ld.x0, ld.x1, ld.y0, ld.y0, 'top', width);
  }
  if (model.depthSide === 'left') {
    planDimV(ctx, Math.min(gb.x0, ld.x0) - off, ld.y0, ld.y1, ld.x0, 'left', depth);
  } else {
    planDimV(ctx, Math.max(gb.x1, ld.x1) + off, ld.y0, ld.y1, ld.x1, 'right', depth);
  }
}

/**
 * Small note naming the whole arriving flight ("10 TR @ 11""), since only its
 * last treads are drawn: beyond the break line for up / down stubs, under the
 * stub for a sideways (L) one.
 *
 * @param {object} ctx
 * @param {object} f         stub
 * @param {object} arriving  { treads, d } of the whole arriving flight
 */
function planDrawStubNote(ctx, f, arriving) {
  const fs = ctx.fs, capH = PLAN_CAP_H * fs;
  const str = planTreadText(arriving);
  const clear = Math.min(PLAN_BREAK_ZIG * fs, f.tail * 0.45) + 0.8 * fs;   // past the zig-zag
  if (f.dir === 'up') {
    planText(ctx, (f.x0 + f.x1) / 2, f.y1 + clear + capH, str, fs, 'middle', {});
  } else if (f.dir === 'down') {
    planText(ctx, (f.x0 + f.x1) / 2, f.y0 - clear, str, fs, 'middle', {});
  } else {
    // Under the stub, centred on it but never past its landing end.
    const tw = planTextW(str, fs);
    const cx = Math.min((f.x0 + f.x1) / 2, f.x1 - 0.3 * fs - tw / 2);
    planText(ctx, cx, f.y1 + 0.8 * fs + capH, str, fs, 'middle', {});
  }
}

/* =============================================================================
 * Labels (leader notes in columns left and right of the drawing)
 * ========================================================================== */

/**
 * Remember a leader label; it is placed once all steel and dimensions are
 * drawn, in a column outside everything on `side`.
 *
 * @param {object} ctx
 * @param {string} text   may contain "\n"
 * @param {number} ax     anchor (arrow tip) x
 * @param {number} ay     anchor y
 * @param {string} side   'left' | 'right'
 * @param {number} prefY  preferred y of the label's last line
 */
function planQueueLabel(ctx, text, ax, ay, side, prefY) {
  ctx.labels.push({ lines: String(text).split('\n'), ax: ax, ay: ay, side: side, prefY: prefY });
}

/**
 * Place the queued labels: one column per side just outside the drawn
 * extents, stacked top to bottom without overlapping, each with a leader
 * (short horizontal shoulder, then straight to the arrow tip).
 *
 * Labels also steer around text that is already on the sheet (dimension
 * strings, "UP", earlier labels; see ctx.obstacles). If a label's text or its
 * leader would cover or cross one, the label slides up or down its column in
 * half-line steps to the nearest clear spot, without jumping over the label
 * above it. When nothing nearby is clear it stays where it was.
 *
 * @param {object} ctx
 */
function planPlaceLabels(ctx) {
  const fs = ctx.fs, lh = PLAN_TEXT_LINE * fs;
  const colGap = PLAN_LABEL_GAP * fs;
  // Column positions are fixed BEFORE labels extend the extents.
  const colX = { left: ctx.ext.x0 - colGap, right: ctx.ext.x1 + colGap };

  ['left', 'right'].forEach(function (side) {
    const list = ctx.labels.filter(function (l) { return l.side === side; })
      .sort(function (a, b) { return a.prefY - b.prefY; });
    let prevBottom = -Infinity;
    list.forEach(function (l) {
      const n = l.lines.length;
      // y is the middle of the last line; block spans `above` up, `below` down.
      const above = (n - 1) * lh + 0.6 * fs, below = 0.55 * fs;
      let y = l.prefY;
      if (y - above < prevBottom + 0.5 * fs) y = prevBottom + 0.5 * fs + above;
      const minY = prevBottom + 0.5 * fs + above;          // keep below the label above
      // Try y, then y +/- half a line, +/- a line, ... and take the first clear spot.
      const step = lh / 2;
      for (let k = 0; k <= PLAN_LABEL_TRIES; k++) {
        const tries = k === 0 ? [y] : [y + k * step, y - k * step];
        const hit = tries.find(function (cy) {
          return cy >= minY - 1e-9 && !planLabelBlocked(ctx, l, colX[side], cy, side);
        });
        if (hit !== undefined) { y = hit; break; }
      }
      prevBottom = y + below;
      planDrawLabel(ctx, l, colX[side], y, side);
    });
  });
}

/**
 * Would this label, drawn at column x / last-line y, cover or cross any text
 * already on the sheet? Checks every text line of the label and both leader
 * segments (shoulder, then the run to the arrow tip) against ctx.obstacles,
 * each obstacle padded by PLAN_OBSTACLE_PAD x font size.
 * Geometry matches planDrawLabel.
 *
 * @param {object} ctx
 * @param {object} l      queued label
 * @param {number} x      column x
 * @param {number} y      middle of the last text line
 * @param {string} side   'left' | 'right'
 * @returns {boolean}
 */
function planLabelBlocked(ctx, l, x, y, side) {
  const fs = ctx.fs, lh = PLAN_TEXT_LINE * fs, n = l.lines.length, pad = PLAN_OBSTACLE_PAD * fs;
  const inward = side === 'left' ? 1 : -1;
  // The label's own text lines.
  const boxes = l.lines.map(function (line, i) {
    const w = planTextW(line, fs), base = y + 0.35 * fs - (n - 1 - i) * lh;
    const xa = side === 'left' ? x - w : x;
    return { x0: xa, y0: base - PLAN_CAP_H * fs, x1: xa + w, y1: base + 0.25 * fs };
  });
  // Its leader: shoulder from the text, then straight to the arrow tip.
  const sx = x + inward * 0.4 * fs;
  const kx = sx + inward * PLAN_LEADER_SHOULDER * fs;
  const segs = [[sx, y, kx, y], [kx, y, l.ax, l.ay]];
  return ctx.obstacles.some(function (o) {
    const b = { x0: o.x0 - pad, y0: o.y0 - pad, x1: o.x1 + pad, y1: o.y1 + pad };
    return boxes.some(function (bx) { return planBoxesHit(bx, b); }) ||
      segs.some(function (s) { return planSegHitsBox(s[0], s[1], s[2], s[3], b); });
  });
}

/**
 * Draw one label: text lines, leader and arrowhead.
 *
 * @param {object} ctx
 * @param {object} l      queued label
 * @param {number} x      column x (text right edge on the left, left edge on the right)
 * @param {number} y      middle of the last text line
 * @param {string} side   'left' | 'right'
 */
function planDrawLabel(ctx, l, x, y, side) {
  const fs = ctx.fs, lh = PLAN_TEXT_LINE * fs, n = l.lines.length;
  const inward = side === 'left' ? 1 : -1;
  l.lines.forEach(function (line, i) {
    planText(ctx, x, y + 0.35 * fs - (n - 1 - i) * lh, line, fs, side === 'left' ? 'end' : 'start', {});
  });
  // Leader: shoulder from the text, then to the anchor.
  const sx = x + inward * 0.4 * fs;
  const kx = sx + inward * PLAN_LEADER_SHOULDER * fs;
  const hl = PLAN_ARROW_LEN * fs * 0.8;
  const dist = Math.hypot(l.ax - kx, l.ay - y) || 1;
  // Stop the line at the base of the arrowhead.
  const bx = l.ax - (l.ax - kx) / dist * hl, by = l.ay - (l.ay - y) / dist * hl;
  planPolyline(ctx, [{ x: sx, y: y }, { x: kx, y: y }, { x: bx, y: by }], 'sp-leader', ctx.u * PLAN_LEADER_U);
  planArrowHead(ctx, l.ax, l.ay, kx, y, hl, hl * 0.3);
}

