/**
 * Create an SVG element, set attributes, optional text, append it.
 *
 * @param {object} ctx
 * @param {string} tag
 * @param {object} attrs
 * @param {string} [text]
 * @param {Node} [parent]  defaults to the drawing root
 * @returns {SVGElement}
 */
function planEl(ctx, tag, attrs, text, parent) {
  const el = ctx.doc.createElementNS(PLAN_SVG_NS, tag);
  planSetAttrs(el, attrs);
  if (text != null) el.textContent = text;
  (parent || ctx.root).appendChild(el);
  return el;
}

/**
 * Set attributes; numbers are rounded to 0.01 to keep the markup small.
 *
 * @param {Element} el
 * @param {object} attrs
 */
function planSetAttrs(el, attrs) {
  for (const k in attrs) {
    const v = attrs[k];
    el.setAttribute(k, typeof v === 'number' ? String(planR(v)) : String(v));
  }
}

/**
 * Straight line, also grows the extents.
 *
 * @param {object} ctx
 * @param {number} x1, y1, x2, y2
 * @param {string} cls  CSS class
 * @param {number} w    stroke width
 */
function planLine(ctx, x1, y1, x2, y2, cls, w) {
  planEl(ctx, 'line', { class: cls, fill: 'none', x1: x1, y1: y1, x2: x2, y2: y2, 'stroke-width': w });
  planExt(ctx, x1, y1); planExt(ctx, x2, y2);
}

/**
 * Open polyline through points, also grows the extents.
 *
 * @param {object} ctx
 * @param {{x:number,y:number}[]} pts
 * @param {string} cls
 * @param {number} w
 */
function planPolyline(ctx, pts, cls, w) {
  planEl(ctx, 'polyline', { class: cls, fill: 'none', 'stroke-width': w,
    points: pts.map(function (p) { return planR(p.x) + ',' + planR(p.y); }).join(' ') });
  pts.forEach(function (p) { planExt(ctx, p.x, p.y); });
}

/**
 * Filled arrowhead with its tip at (tx, ty), pointing away from (fx, fy).
 *
 * @param {object} ctx
 * @param {number} tx, ty   tip
 * @param {number} fx, fy   any point back along the shaft
 * @param {number} len      head length
 * @param {number} half     head half-width
 */
function planArrowHead(ctx, tx, ty, fx, fy, len, half) {
  const d = Math.hypot(tx - fx, ty - fy) || 1;
  const ux = (tx - fx) / d, uy = (ty - fy) / d;              // unit vector to tip
  const bx = tx - ux * len, by = ty - uy * len;              // base centre
  const pts = [[tx, ty], [bx - uy * half, by + ux * half], [bx + uy * half, by - ux * half]];
  planEl(ctx, 'polygon', { class: 'sp-head', fill: '#0b0b0b',
    points: pts.map(function (p) { return planR(p[0]) + ',' + planR(p[1]); }).join(' ') });
}

/**
 * Text element with halo. Grows the extents by an estimate of its size.
 *
 * @param {object} ctx
 * @param {number} x, y      anchor point (baseline)
 * @param {string} str
 * @param {number} size      font size (in)
 * @param {string} anchor    'start' | 'middle' | 'end'
 * @param {object} opt       { rotate: bool (-90 about x,y), dim: bool (mono, dim colour),
 *                            title: bool, key: bool (bold axis key letter) }
 */
function planText(ctx, x, y, str, size, anchor, opt) {
  const cls = opt.dim ? 'sp-dimtext' : 'sp-text' + (opt.title ? ' sp-title' : '') + (opt.key ? ' sp-keytext' : '');
  const attrs = {
    class: cls, x: x, y: y, 'font-size': size, 'text-anchor': anchor,
    fill: opt.dim ? '#ff4f00' : '#0b0b0b',
    'stroke-width': size * PLAN_TEXT_HALO,
  };
  if (opt.rotate) attrs.transform = 'rotate(-90 ' + planR(x) + ' ' + planR(y) + ')';
  planEl(ctx, 'text', attrs, str);

  // Extents estimate: width along the baseline, cap height above it.
  const w = planTextW(str, size, !!opt.dim) * (opt.title ? 1.06 : 1);
  const a0 = anchor === 'start' ? 0 : anchor === 'end' ? -w : -w / 2;
  let box;
  if (opt.rotate) {
    box = [x - size * PLAN_CAP_H, y - a0 - w, x + size * 0.25, y - a0];
  } else {
    box = [x + a0, y - size * PLAN_CAP_H, x + a0 + w, y + size * 0.25];
  }
  planExt(ctx, box[0], box[1]);
  planExt(ctx, box[2], box[3]);
  // Remember where the text is, so leader labels placed later steer around it
  // (dimension text, "UP", and each label once it is drawn).
  planAddObstacle(ctx, box[0], box[1], box[2], box[3]);
}

/**
 * Record a rectangle that leader labels must not cover or cross.
 *
 * @param {object} ctx
 * @param {number} x0  left (in)
 * @param {number} y0  top (in)
 * @param {number} x1  right (in)
 * @param {number} y1  bottom (in)
 */
function planAddObstacle(ctx, x0, y0, x1, y1) {
  if (!ctx.obstacles) return;
  if (![x0, y0, x1, y1].every(isFinite)) return;
  ctx.obstacles.push({ x0: Math.min(x0, x1), y0: Math.min(y0, y1), x1: Math.max(x0, x1), y1: Math.max(y0, y1) });
}

/**
 * True when the segment (ax, ay) -> (bx, by) passes through the box
 * (Liang-Barsky clipping: shrink the segment's 0..1 range against each edge).
 *
 * @param {number} ax
 * @param {number} ay
 * @param {number} bx
 * @param {number} by
 * @param {{x0:number,y0:number,x1:number,y1:number}} b
 * @returns {boolean}
 */
function planSegHitsBox(ax, ay, bx, by, b) {
  const dx = bx - ax, dy = by - ay;
  let t0 = 0, t1 = 1;
  // Each pair is (p, q) for one edge: the segment is inside where p*t <= q.
  const edges = [[-dx, ax - b.x0], [dx, b.x1 - ax], [-dy, ay - b.y0], [dy, b.y1 - ay]];
  for (let i = 0; i < 4; i++) {
    const p = edges[i][0], q = edges[i][1];
    if (p === 0) { if (q < 0) return false; continue; }    // parallel and outside
    const r = q / p;
    if (p < 0) { if (r > t1) return false; if (r > t0) t0 = r; }
    else { if (r < t0) return false; if (r < t1) t1 = r; }
  }
  return t0 <= t1;
}

/**
 * True when two boxes overlap.
 *
 * @param {{x0:number,y0:number,x1:number,y1:number}} a
 * @param {{x0:number,y0:number,x1:number,y1:number}} b
 * @returns {boolean}
 */
function planBoxesHit(a, b) {
  return a.x0 < b.x1 && b.x0 < a.x1 && a.y0 < b.y1 && b.y0 < a.y1;
}

/**
 * Estimated text width.
 *
 * @param {string} str
 * @param {number} size
 * @param {boolean} [mono]  true for the monospace dimension font
 * @returns {number}
 */
function planTextW(str, size, mono) {
  return String(str).length * size * (mono ? PLAN_MONO_CHAR_W : PLAN_CHAR_W);
}

/**
 * Grow the drawn extents to include (x, y).
 *
 * @param {object} ctx
 * @param {number} x
 * @param {number} y
 */
function planExt(ctx, x, y) {
  if (!isFinite(x) || !isFinite(y)) return;
  const e = ctx.ext;
  if (x < e.x0) e.x0 = x;
  if (x > e.x1) e.x1 = x;
  if (y < e.y0) e.y0 = y;
  if (y > e.y1) e.y1 = y;
}

