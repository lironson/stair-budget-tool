/**
 * Clamp a number.
 *
 * @param {number} v
 * @param {number} lo
 * @param {number} hi
 * @returns {number}
 */
function planClamp(v, lo, hi) {
  return Math.min(hi, Math.max(lo, v));
}

/**
 * Read any value as a finite number, use `def` if it is not one, then clamp.
 *
 * @param {*} v
 * @param {number} def
 * @param {number} lo
 * @param {number} hi
 * @returns {number}
 */
function planNum(v, def, lo, hi) {
  let n = (v === '' || v === null || v === undefined) ? NaN : Number(v);
  if (!isFinite(n)) n = def;
  return planClamp(n, lo, hi);
}

/**
 * Round to 0.01 for compact SVG attributes.
 *
 * @param {number} v
 * @returns {number}
 */
function planR(v) {
  return Math.round(v * 100) / 100;
}

/**
 * Feet-inches text. Uses fmtFtIn() from calc.js when it is loaded; otherwise
 * a local copy of the same format (nearest 1/8"), so the plan still draws if
 * calc.js is missing or has not loaded yet.
 *
 * @param {number} inches
 * @returns {string}  e.g. 9'-2"
 */
function planFmtFtIn(inches) {
  if (typeof fmtFtIn === 'function') return fmtFtIn(inches);
  const e = Math.round(Math.abs(Number(inches) || 0) * 8);  // eighths
  const ft = Math.floor(e / 96), rest = e - ft * 96;
  return ft + "'-" + planInchText(rest) + '"';
}

/**
 * Inches with a fraction, e.g. 11 -> 11"   10.5 -> 10 1/2".
 *
 * @param {number} inches
 * @returns {string}
 */
function planFmtIn(inches) {
  return planInchText(Math.round(Math.abs(inches) * 8)) + '"';
}

/**
 * Eighths of an inch as "W N/D" (no inch mark).
 *
 * @param {number} eighths  whole number of eighths
 * @returns {string}
 */
function planInchText(eighths) {
  const whole = Math.floor(eighths / 8);
  let num = eighths % 8, den = 8;
  while (num > 0 && num % 2 === 0) { num /= 2; den /= 2; }
  return whole + (num > 0 ? ' ' + num + '/' + den : '');
}
