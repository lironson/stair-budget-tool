/**
 * Drawing title in the style of the reference sheets:
 *      1 | STAIR FRAMING PLAN
 *     ---+--------------------   (heavy rule)
 *        | SCALE: NTS
 * Centred under the stair, below everything else.
 *
 * @param {object} ctx
 * @param {object} gb  stair bounds
 * @returns {{x0:number, x1:number, top:number, bottom:number}}  the title
 *          block's box, so the axis key can sit beside it
 */
function planDrawTitle(ctx, gb) {
  const fs = ctx.fs, ts = fs * PLAN_TITLE_SIZE;
  const titleW = planTextW(PLAN_TEXT.title, ts) * 1.06;     // bold is a bit wider
  const numW = ts * 1.3;
  const total = numW + 0.5 * fs + titleW;
  const x0 = (gb.x0 + gb.x1) / 2 - total / 2;
  const base = ctx.ext.y1 + 1.8 * fs + ts * PLAN_CAP_H;     // title baseline
  const ruleY = base + 0.35 * fs;
  const divX = x0 + numW;

  planText(ctx, x0 + numW / 2, base, PLAN_TEXT.detail, ts, 'middle', {});
  planText(ctx, divX + 0.5 * fs, base, PLAN_TEXT.title, ts, 'start', { title: true });
  planLine(ctx, x0, ruleY, x0 + total, ruleY, 'sp-ink', ctx.u * 0.7);           // heavy rule
  planLine(ctx, divX, base - ts * 0.95, divX, ruleY + 1.4 * fs, 'sp-ink', ctx.u * 0.18);
  planText(ctx, divX + 0.5 * fs, ruleY + 1.1 * fs, PLAN_TEXT.scale, fs * PLAN_SCALE_SIZE, 'start', {});
  return { x0: x0, x1: x0 + total, top: base - ts * PLAN_CAP_H, bottom: ruleY + 1.4 * fs };
}

/**
 * Small axis key to the right of the title block:
 *
 *        Y
 *        ^
 *        |
 *        +----> X
 *
 * X = across flight 1's travel (the "X beams - across the stair" input),
 * Y = flight 1's direction of travel, up the screen ("Y beams - along the
 * stair"). Muted arrows, small ink letters; it sits level with the title
 * block, below the stair and every label, and grows the extents so the
 * viewBox includes it. Drawn only when the landing has beams.
 *
 * @param {object} ctx
 * @param {{x0:number, x1:number, top:number, bottom:number}} tb  title block box
 */
function planDrawAxisKey(ctx, tb) {
  const fs = ctx.fs, ks = fs * PLAN_KEY_SIZE;
  const len = PLAN_KEY_LEN * ks;
  const w = ctx.u * PLAN_DIM_U * 1.2;
  const hl = ks * 0.55, hw = hl * 0.38;
  // Origin: bottom-left corner of the key, level with the bottom of the title
  // block; the Y arrow then reaches about the title's cap height.
  const ox = tb.x1 + 2.2 * fs;
  const oy = Math.max(tb.bottom - 0.3 * fs, tb.top + len + 0.9 * ks);
  const head = function (tx, ty, fx, fy) {
    const d = Math.hypot(tx - fx, ty - fy) || 1;
    const ux = (tx - fx) / d, uy = (ty - fy) / d, bx = tx - ux * hl, by = ty - uy * hl;
    planEl(ctx, 'polygon', { class: 'sp-keyhead', fill: '#767676', points: [
      [tx, ty], [bx - uy * hw, by + ux * hw], [bx + uy * hw, by - ux * hw],
    ].map(function (p) { return planR(p[0]) + ',' + planR(p[1]); }).join(' ') });
  };
  // X: to the right. Y: up the screen (flight 1's direction of travel).
  planLine(ctx, ox, oy, ox + len - hl * 0.9, oy, 'sp-key', w);
  head(ox + len, oy, ox, oy);
  planLine(ctx, ox, oy, ox, oy - len + hl * 0.9, 'sp-key', w);
  head(ox, oy - len, ox, oy);
  planExt(ctx, ox + len, oy); planExt(ctx, ox, oy - len);
  planText(ctx, ox + len + 0.35 * ks, oy + 0.36 * ks, PLAN_TEXT.axisX, ks, 'start', { key: true });
  planText(ctx, ox, oy - len - 0.4 * ks, PLAN_TEXT.axisY, ks, 'middle', { key: true });
}

/* =============================================================================
 * Low-level SVG helpers
 * ========================================================================== */

/**
 * Create an SVG element, set attributes, optional text, append it.
 *
 * @param {object} ctx
 * @param {string} tag
 * @param {object} attrs
 * @param {string} [text]
 * @param {Node} [parent]  defaults to the drawing root
 * @returns {SVGElement}
 */
function planEl(ctx, tag, attrs, text, parent) {
  const el = ctx.doc.createElementNS(PLAN_SVG_NS, tag);
  planSetAttrs(el, attrs);
  if (text != null) el.textContent = text;
  (parent || ctx.root).appendChild(el);
  return el;
}

/**
 * Set attributes; numbers are rounded to 0.01 to keep the markup small.
 *
 * @param {Element} el
 * @param {object} attrs
 */
function planSetAttrs(el, attrs) {
  for (const k in attrs) {
    const v = attrs[k];
    el.setAttribute(k, typeof v === 'number' ? String(planR(v)) : String(v));
  }
}

/**
 * Straight line, also grows the extents.
 *
 * @param {object} ctx
 * @param {number} x1, y1, x2, y2
 * @param {string} cls  CSS class
 * @param {number} w    stroke width
 */
function planLine(ctx, x1, y1, x2, y2, cls, w) {
  planEl(ctx, 'line', { class: cls, fill: 'none', x1: x1, y1: y1, x2: x2, y2: y2, 'stroke-width': w });
  planExt(ctx, x1, y1); planExt(ctx, x2, y2);
}

/**
 * Open polyline through points, also grows the extents.
 *
 * @param {object} ctx
 * @param {{x:number,y:number}[]} pts
 * @param {string} cls
 * @param {number} w
 */
function planPolyline(ctx, pts, cls, w) {
  planEl(ctx, 'polyline', { class: cls, fill: 'none', 'stroke-width': w,
    points: pts.map(function (p) { return planR(p.x) + ',' + planR(p.y); }).join(' ') });
  pts.forEach(function (p) { planExt(ctx, p.x, p.y); });
}

/**
 * Filled arrowhead with its tip at (tx, ty), pointing away from (fx, fy).
 *
 * @param {object} ctx
 * @param {number} tx, ty   tip
 * @param {number} fx, fy   any point back along the shaft
 * @param {number} len      head length
 * @param {number} half     head half-width
 */
function planArrowHead(ctx, tx, ty, fx, fy, len, half) {
  const d = Math.hypot(tx - fx, ty - fy) || 1;
  const ux = (tx - fx) / d, uy = (ty - fy) / d;              // unit vector to tip
  const bx = tx - ux * len, by = ty - uy * len;              // base centre
  const pts = [[tx, ty], [bx - uy * half, by + ux * half], [bx + uy * half, by - ux * half]];
  planEl(ctx, 'polygon', { class: 'sp-head', fill: '#0b0b0b',
    points: pts.map(function (p) { return planR(p[0]) + ',' + planR(p[1]); }).join(' ') });
}

/**
 * Text element with halo. Grows the extents by an estimate of its size.
 *
 * @param {object} ctx
 * @param {number} x, y      anchor point (baseline)
 * @param {string} str
 * @param {number} size      font size (in)
 * @param {string} anchor    'start' | 'middle' | 'end'
 * @param {object} opt       { rotate: bool (-90 about x,y), dim: bool (mono, dim colour),
 *                            title: bool, key: bool (bold axis key letter) }
 */
function planText(ctx, x, y, str, size, anchor, opt) {
  const cls = opt.dim ? 'sp-dimtext' : 'sp-text' + (opt.title ? ' sp-title' : '') + (opt.key ? ' sp-keytext' : '');
  const attrs = {
    class: cls, x: x, y: y, 'font-size': size, 'text-anchor': anchor,
    fill: opt.dim ? '#ff4f00' : '#0b0b0b',
    'stroke-width': size * PLAN_TEXT_HALO,
  };
  if (opt.rotate) attrs.transform = 'rotate(-90 ' + planR(x) + ' ' + planR(y) + ')';
  planEl(ctx, 'text', attrs, str);

  // Extents estimate: width along the baseline, cap height above it.
  const w = planTextW(str, size, !!opt.dim) * (opt.title ? 1.06 : 1);
  const a0 = anchor === 'start' ? 0 : anchor === 'end' ? -w : -w / 2;
  if (opt.rotate) {
    planExt(ctx, x - size * PLAN_CAP_H, y - a0 - w);
    planExt(ctx, x + size * 0.25, y - a0);
  } else {
    planExt(ctx, x + a0, y - size * PLAN_CAP_H);
    planExt(ctx, x + a0 + w, y + size * 0.25);
  }
}

/**
 * Estimated text width.
 *
 * @param {string} str
 * @param {number} size
 * @param {boolean} [mono]  true for the monospace dimension font
 * @returns {number}
 */
function planTextW(str, size, mono) {
  return String(str).length * size * (mono ? PLAN_MONO_CHAR_W : PLAN_CHAR_W);
}

/**
 * Grow the drawn extents to include (x, y).
 *
 * @param {object} ctx
 * @param {number} x
 * @param {number} y
 */
function planExt(ctx, x, y) {
  if (!isFinite(x) || !isFinite(y)) return;
  const e = ctx.ext;
  if (x < e.x0) e.x0 = x;
  if (x > e.x1) e.x1 = x;
  if (y < e.y0) e.y0 = y;
  if (y > e.y1) e.y1 = y;
}

/* =============================================================================
 * Small utilities
 * ========================================================================== */

/**
 * Clamp a number.
 *
 * @param {number} v
 * @param {number} lo
 * @param {number} hi
 * @returns {number}
 */
function planClamp(v, lo, hi) {
  return Math.min(hi, Math.max(lo, v));
}

/**
 * Read any value as a finite number, use `def` if it is not one, then clamp.
 *
 * @param {*} v
 * @param {number} def
 * @param {number} lo
 * @param {number} hi
 * @returns {number}
 */
function planNum(v, def, lo, hi) {
  let n = (v === '' || v === null || v === undefined) ? NaN : Number(v);
  if (!isFinite(n)) n = def;
  return planClamp(n, lo, hi);
}

/**
 * Round to 0.01 for compact SVG attributes.
 *
 * @param {number} v
 * @returns {number}
 */
function planR(v) {
  return Math.round(v * 100) / 100;
}

/**
 * Feet-inches text. Uses fmtFtIn() from calc.js when it is loaded; otherwise
 * a local copy of the same format (nearest 1/8"), so the plan still draws if
 * calc.js is missing or has not loaded yet.
 *
 * @param {number} inches
 * @returns {string}  e.g. 9'-2"
 */
function planFmtFtIn(inches) {
  if (typeof fmtFtIn === 'function') return fmtFtIn(inches);
  const e = Math.round(Math.abs(Number(inches) || 0) * 8);  // eighths
  const ft = Math.floor(e / 96), rest = e - ft * 96;
  return ft + "'-" + planInchText(rest) + '"';
}

/**
 * Inches with a fraction, e.g. 11 -> 11"   10.5 -> 10 1/2".
 *
 * @param {number} inches
 * @returns {string}
 */
function planFmtIn(inches) {
  return planInchText(Math.round(Math.abs(inches) * 8)) + '"';
}

/**
 * Eighths of an inch as "W N/D" (no inch mark).
 *
 * @param {number} eighths  whole number of eighths
 * @returns {string}
 */
function planInchText(eighths) {
  const whole = Math.floor(eighths / 8);
  let num = eighths % 8, den = 8;
  while (num > 0 && num % 2 === 0) { num /= 2; den /= 2; }
  return whole + (num > 0 ? ' ' + num + '/' + den : '');
}
