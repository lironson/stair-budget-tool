/* =============================================================================
 * Public entry point
 * ========================================================================== */

/**
 * Clear `svgEl` and draw the stair framing plan for `state`.
 * Safe to call on every input event; it never throws.
 *
 * @param {SVGSVGElement} svgEl  the <svg id="plan"> element
 * @param {object} state         the shared state object (ARCHITECTURE.md §1)
 */
function renderPlan(svgEl, state) {
  if (!svgEl || typeof svgEl.appendChild !== 'function') return;
  try {
    planRender(svgEl, state || {});
  } catch (err) {
    // A drawing bug must never break the estimator: show a note instead.
    try {
      if (typeof console !== 'undefined') console.warn('renderPlan:', err);
      planRenderError(svgEl);
    } catch (e) { /* give up quietly */ }
  }
}

/* =============================================================================
 * Main pipeline
 * ========================================================================== */

/**
 * Does the real work for renderPlan(): normalise input, lay out, draw, fit.
 *
 * @param {SVGSVGElement} svgEl
 * @param {object} state
 */
function planRender(svgEl, state) {
  const g = planReadState(state);          // clamped numbers + label strings
  const model = planLayout(g);              // flights + landing positions (in)

  // Size of the stair itself drives the unit, text size and line weights.
  const gb = planGeomBounds(model, g);
  const size = Math.max(gb.x1 - gb.x0, gb.y1 - gb.y0, 24);
  const u = planClamp(size * PLAN_UNIT_RATIO, PLAN_UNIT_MIN, PLAN_UNIT_MAX);

  const doc = svgEl.ownerDocument || document;
  const ctx = {
    doc: doc,
    root: doc.createDocumentFragment(),     // build off-DOM, attach once
    u: u,
    fs: u * PLAN_FONT_U,                    // font size in inches
    ext: { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity },
    labels: [],                             // leader labels, placed at the end
    g: g,
  };

  // <style> and <title> go first, then a paper rect we size at the very end.
  planEl(ctx, 'style', {}, PLAN_CSS);
  planEl(ctx, 'title', {}, 'Stair framing plan, ' + g.orientation);
  const paper = planEl(ctx, 'rect', { class: 'sp-paper', fill: '#ffffff' });

  // --- the stair itself -----------------------------------------------------
  if (model.landing) planDrawLandingFill(ctx, model.landing);
  model.flights.forEach(function (f) { planDrawTreads(ctx, f); });
  if (model.landing) planDrawLandingSteel(ctx, model.landing, model.chainSide);
  model.flights.forEach(function (f) { planDrawStringers(ctx, f); });
  model.flights.forEach(function (f) { planDrawUpArrow(ctx, f); });

  // --- annotation -----------------------------------------------------------
  planDrawDimensions(ctx, model, gb);
  planPlaceLabels(ctx);
  const tb = planDrawTitle(ctx, gb);
  if (model.landing && (g.nBeamsX > 0 || g.nBeamsY > 0)) planDrawAxisKey(ctx, tb);

  // Fit the viewBox around everything drawn, plus a margin.
  const m = ctx.fs * PLAN_MARGIN;
  const e = ctx.ext;
  const vb = [e.x0 - m, e.y0 - m, (e.x1 - e.x0) + 2 * m, (e.y1 - e.y0) + 2 * m].map(planR);
  planSetAttrs(paper, { x: vb[0], y: vb[1], width: vb[2], height: vb[3] });

  // Swap the new drawing in.
  while (svgEl.firstChild) svgEl.removeChild(svgEl.firstChild);
  svgEl.setAttribute('viewBox', vb.join(' '));
  svgEl.setAttribute('preserveAspectRatio', 'xMidYMid meet');
  svgEl.setAttribute('role', 'img');
  svgEl.setAttribute('aria-label', 'Stair framing plan: ' + g.orientation + ', ' +
    g.treads1 + (g.hasFlight2 ? ' + ' + g.treads2 : '') + ' treads');
  svgEl.appendChild(ctx.root);
}

/**
 * Fallback drawing when something went wrong: a short note on the sheet.
 *
 * @param {SVGSVGElement} svgEl
 */
function planRenderError(svgEl) {
  while (svgEl.firstChild) svgEl.removeChild(svgEl.firstChild);
  svgEl.setAttribute('viewBox', '0 0 200 60');
  const t = (svgEl.ownerDocument || document).createElementNS(PLAN_SVG_NS, 'text');
  planSetAttrs(t, { x: 100, y: 34, 'text-anchor': 'middle', 'font-size': 8, fill: '#767676',
    'font-family': PLAN_FONT });
  t.textContent = 'PLAN VIEW UNAVAILABLE FOR THESE INPUTS';
  svgEl.appendChild(t);
}

/* =============================================================================
 * Input normalisation
 * ========================================================================== */

/**
 * Read `state` into a clean geometry object `g`, clamping every number so the
 * layout can trust it. Missing values fall back to the contract defaults.
 *
 * @param {object} state
 * @returns {object} g  { orientation, treads1, treads2, d, W, L, G, nStringers,
 *                        nBeamsX, nBeamsY, stringerName, beamXName, beamYName,
 *                        hasFlight2, run1, run2 }
 */
function planReadState(state) {
  const orientation = PLAN_ORIENTATIONS.indexOf(state.orientation) >= 0 ? state.orientation : 'U-right';
  const g = {
    orientation: orientation,
    treads1: Math.round(planNum(state.treads1, 10, 0, PLAN_MAX_TREADS)),
    treads2: Math.round(planNum(state.treads2, 10, 0, PLAN_MAX_TREADS)),
    d: planNum(state.treadDepth, 11, PLAN_MIN_TREAD_DEPTH, PLAN_MAX_TREAD_DEPTH),
    W: planNum(state.stairWidth, 44, PLAN_MIN_WIDTH, PLAN_MAX_WIDTH),
    L: planNum(state.landingDepth, 48, 0, PLAN_MAX_LANDING),
    G: planNum(state.wellGap, 4, 0, PLAN_MAX_WELL),
    // 2 = outer pair only, 3 = one inner at the centre, 4 = two inner.
    nStringers: Math.round(planNum(state.stringersPerFlight, 2, 2, 4)),
    // Landing beams per landing: X = across flight 1's travel, Y = along it.
    nBeamsX: Math.round(planNum(state.beamXCount, 2, 0, PLAN_MAX_BEAMS)),
    nBeamsY: Math.round(planNum(state.beamYCount, 2, 0, PLAN_MAX_BEAMS)),
    stringerName: planSectionName(state.stringerSection, state.stringerCustomLbFt, 'C12x20.7'),
    beamXName: planSectionName(state.beamXSection, state.beamXCustomLbFt, 'C8x11.2'),
    beamYName: planSectionName(state.beamYSection, state.beamYCustomLbFt, 'C8x11.2'),
  };
  g.hasFlight2 = orientation !== 'straight';
  if (!g.hasFlight2) g.treads2 = 0;
  g.run1 = g.treads1 * g.d;                 // horizontal run of flight 1
  g.run2 = g.treads2 * g.d;                 // horizontal run of flight 2
  return g;
}

/**
 * Text shown for a channel size: the section name, or "CUSTOM 20 LB/FT".
 *
 * @param {string} name       state.*Section
 * @param {number} customLbFt state.*CustomLbFt
 * @param {string} fallback   used when the name is empty
 * @returns {string}
 */
function planSectionName(name, customLbFt, fallback) {
  if (name === 'Custom') {
    return PLAN_TEXT.custom.replace('{LBFT}', String(Math.round(planNum(customLbFt, 0, 0, 9999) * 100) / 100));
  }
  const s = (typeof name === 'string' && name.trim()) ? name.trim() : fallback;
  return s.slice(0, 24);
}

/* =============================================================================
 * Layout (ARCHITECTURE.md §3)
 *
 * A "flight" object:
 *   { num, x0, y0, x1, y1,      bounding rectangle (in)
 *     dir,                      travel direction going UP the stair:
 *                               'up' | 'down' | 'left' | 'right' (on screen)
 *     run, width, treads, d,
 *     landingAt,                'end' (flight 1) or 'start' (flight 2): which
 *                               end meets the landing, gets the crank jog
 *     labelCol,                 'left' | 'right' label column for its labels
 *     labelEdge,                'min' | 'max': which outer stringer is labelled
 *                               (min = the x0 / y0 side)
 *     dimSide }                 'chain' (in the main vertical string with the
 *                               landing), 'left', 'right' or 'top'
 * The model:
 *   { flights: [f1, f2?], landing: {x0,y0,x1,y1,labelCol} | null,
 *     chainSide: 'left' | 'right' }
 * ========================================================================== */

/**
 * Pick the layout function for g.orientation.
 *
 * @param {object} g  from planReadState
 * @returns {object} model
 */
function planLayout(g) {
  switch (g.orientation) {
    case 'straight': return planLayoutStraight(g);
    case 'inline': return planLayoutInline(g);
    case 'L-left': return planLayoutL(g, 'left');
    case 'L-right': return planLayoutL(g, 'right');
    case 'U-left': return planLayoutU(g, 'left');
    default: return planLayoutU(g, 'right');
  }
}

/**
 * Build a flight record. (x0, y0) is the top-left corner of its rectangle;
 * vertical flights are `width` wide and `run` tall, horizontal ones the
 * other way round.
 *
 * @param {number} num        1 or 2
 * @param {number} x0         left edge (in)
 * @param {number} y0         top edge (in)
 * @param {string} dir        'up' | 'down' | 'left' | 'right'
 * @param {number} treads
 * @param {object} g
 * @param {object} extra      labelCol, labelEdge, dimSide, landingAt
 * @returns {object} flight
 */
function planMakeFlight(num, x0, y0, dir, treads, g, extra) {
  const run = treads * g.d;
  const vertical = dir === 'up' || dir === 'down';
  const f = {
    num: num, x0: x0, y0: y0,
    x1: x0 + (vertical ? g.W : run),
    y1: y0 + (vertical ? run : g.W),
    dir: dir, run: run, width: g.W, treads: treads, d: g.d,
  };
  for (const k in extra) f[k] = extra[k];
  return f;
}

/**
 * 'straight': flight 1 going up, landing on top (landingDepth x stairWidth).
 * Labels on the left, dimensions on the right.
 *
 * @param {object} g
 * @returns {object} model
 */
function planLayoutStraight(g) {
  // Flight 1 occupies x 0..W, y -run1..0.
  const f1 = planMakeFlight(1, 0, -g.run1, 'up', g.treads1, g,
    { landingAt: 'end', labelCol: 'left', labelEdge: 'min', dimSide: 'chain' });
  // Landing sits directly above flight 1.
  const landing = planMakeLanding(0, -g.run1 - g.L, g.W, g.L, 'left');
  return { flights: [f1], landing: landing, chainSide: 'right' };
}

/**
 * 'inline': flight 1, the landing, then flight 2 carrying straight on up.
 * Labels on the left, one dimension chain (run 1 / landing / run 2) on the right.
 *
 * @param {object} g
 * @returns {object} model
 */
function planLayoutInline(g) {
  const f1 = planMakeFlight(1, 0, -g.run1, 'up', g.treads1, g,
    { landingAt: 'end', labelCol: 'left', labelEdge: 'min', dimSide: 'chain' });
  const landing = planMakeLanding(0, -g.run1 - g.L, g.W, g.L, 'left');
  // Flight 2 starts at the top edge of the landing and keeps going up.
  const f2 = planMakeFlight(2, 0, -g.run1 - g.L - g.run2, 'up', g.treads2, g,
    { landingAt: 'start', labelCol: 'left', labelEdge: 'min', dimSide: 'chain' });
  return { flights: [f1, f2], landing: landing, chainSide: 'right' };
}

/**
 * 'L-left' / 'L-right': flight 1 up to a landingDepth x stairWidth landing;
 * flight 2 leaves the landing's left/right side turned 90 degrees, flush with
 * the far (top) edge of the landing.
 * Flight 1 and the landing are labelled and dimensioned on the side away from
 * flight 2; flight 2 is labelled from the column beyond its far end and
 * dimensioned above.
 *
 * @param {object} g
 * @param {string} turn  'left' | 'right'
 * @returns {object} model
 */
function planLayoutL(g, turn) {
  const outside = turn === 'left' ? 'right' : 'left';   // side away from flight 2
  const f1 = planMakeFlight(1, 0, -g.run1, 'up', g.treads1, g,
    { landingAt: 'end', labelCol: outside, labelEdge: outside === 'left' ? 'min' : 'max', dimSide: 'chain' });
  const yTop = -g.run1 - g.L;                            // far edge of the landing
  const landing = planMakeLanding(0, yTop, g.W, g.L, outside);
  // Flight 2: top edge flush with the landing's far edge, running sideways.
  const x0 = turn === 'left' ? -g.run2 : g.W;
  const f2 = planMakeFlight(2, x0, yTop, turn, g.treads2, g,
    { landingAt: 'start', labelCol: turn, labelEdge: 'min', dimSide: 'top' });
  return { flights: [f1, f2], landing: landing, chainSide: outside };
}

/**
 * 'U-left' / 'U-right': flight 1 up to a full-width landing
 * (2 x stairWidth + wellGap), flight 2 comes back down beside flight 1 on the
 * left/right, with wellGap between the two flights.
 * Each flight is labelled and dimensioned on its own outside face; the landing
 * label goes on flight 2's side to balance the two label columns.
 *
 * @param {object} g
 * @param {string} turn  'left' | 'right'
 * @returns {object} model
 */
function planLayoutU(g, turn) {
  const right = turn === 'right';
  const f1Side = right ? 'left' : 'right';              // flight 1's outside face
  const f1 = planMakeFlight(1, 0, -g.run1, 'up', g.treads1, g,
    { landingAt: 'end', labelCol: f1Side, labelEdge: right ? 'min' : 'max', dimSide: 'chain' });
  // Landing spans both flights and the well between them.
  const lw = 2 * g.W + g.G;
  const lx0 = right ? 0 : -(g.W + g.G);
  const landing = planMakeLanding(lx0, -g.run1 - g.L, lw, g.L, turn);
  // Flight 2 starts at the landing's near edge (y = -run1) and travels down.
  const f2x0 = right ? g.W + g.G : -(g.W + g.G);
  const f2 = planMakeFlight(2, f2x0, -g.run1, 'down', g.treads2, g,
    { landingAt: 'start', labelCol: turn, labelEdge: right ? 'max' : 'min', dimSide: turn });
  return { flights: [f1, f2], landing: landing, chainSide: f1Side };
}

/**
 * Build a landing record, or null when the landing depth is 0.
 *
 * @param {number} x0        left edge (in)
 * @param {number} y0        top (far) edge (in)
 * @param {number} width     across flight 1's travel (in)
 * @param {number} depth     along flight 1's travel (in)
 * @param {string} labelCol  'left' | 'right' column for its beam labels
 * @returns {object|null}
 */
function planMakeLanding(x0, y0, width, depth, labelCol) {
  if (!(depth > 0.01)) return null;
  return { x0: x0, y0: y0, x1: x0 + width, y1: y0 + depth, labelCol: labelCol };
}

/**
 * Bounding box of the stair (flights + landing), ignoring annotation.
 *
 * @param {object} model
 * @param {object} g
 * @returns {{x0:number,y0:number,x1:number,y1:number}}
 */
function planGeomBounds(model, g) {
  const b = { x0: 0, y0: 0, x1: g.W, y1: 0 };           // always include flight 1's foot
  const rects = model.flights.filter(function (f) { return f.run > 0; });
  if (model.landing) rects.push(model.landing);
  rects.forEach(function (r) {
    b.x0 = Math.min(b.x0, r.x0); b.y0 = Math.min(b.y0, r.y0);
    b.x1 = Math.max(b.x1, r.x1); b.y1 = Math.max(b.y1, r.y1);
  });
  return b;
}

