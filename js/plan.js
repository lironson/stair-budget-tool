/* =============================================================================
 * plan.js  —  live STAIR FRAMING PLAN for the Stair Budget Tool
 * =============================================================================
 *
 * WHAT THIS FILE DOES
 *   Defines two public functions:
 *
 *       renderPlan(svgEl, state)           drawing 1, <svg id="plan">
 *       renderUpperLanding(svgEl, state)   drawing 2, <svg id="planUpper">
 *
 *   renderPlan wipes the <svg id="plan"> and redraws a simplified structural
 *   framing plan (like the shop's reference drawings) from the `state` object
 *   described in docs/ARCHITECTURE.md §1:
 *     - thin tread nosing lines on every flight,
 *     - bold channel stringers ("C12x20.7 CRANKED STRINGER"), with a short jog
 *       at the landing end to mark the crank, plus inner stringers when
 *       stringersPerFlight is 4,
 *     - the landing with its hatched-oval deck symbol and its landing beams
 *       in both directions, each axis with its own size and count:
 *         X beams run ACROSS flight 1's travel (horizontal on the plan; these
 *           were the old "landing channels"),
 *         Y beams run ALONG flight 1's travel (vertical on the plan),
 *       with one "C8x11.2 @ LANDING LEVEL" label per axis that has beams,
 *     - an "UP" arrow on each flight,
 *     - dimension strings ("10 TR @ 11"" / 9'-2"), the stair width and the
 *       landing depth, with 45-degree tick marks,
 *     - a small drawing title "1 | STAIR FRAMING PLAN / SCALE: NTS", with a
 *       tiny "X ->  Y ^" axis key beside it (Y = flight 1's direction of
 *       travel, up the screen) that ties the beams to the "X beams" /
 *       "Y beams" inputs.
 *   renderUpperLanding draws the UPPER LANDING (only when landingCount >= 2;
 *   otherwise it leaves its svg empty): the landing at the top of the last
 *   flight, the same size and with the same beams, labels, deck symbol and
 *   width / depth dimensions as landing 1, plus the last 3 treads of the
 *   arriving flight cut off with a zig-zag break line, titled
 *   "2 | UPPER LANDING FRAMING PLAN". Its text is sized from the MAIN stair,
 *   so both drawings read at the same text size.
 *   Both are called on every input event, so they are cheap and they NEVER
 *   throw: odd input (0 treads, huge widths, text in number fields) is clamped.
 *
 * COORDINATE SYSTEM
 *   Everything is drawn in INCHES (1 SVG user unit = 1 inch), x to the right,
 *   y DOWN (normal SVG). Flight 1 starts at y = 0 (its bottom edge) with its
 *   left edge at x = 0 and travels UP the screen (towards negative y). The
 *   viewBox is fitted around whatever was drawn, so negative coordinates are
 *   fine. Text sizes and line weights are multiples of a "unit" that grows with
 *   the size of the stair, so a 3-tread stair and a 25-tread stair both read
 *   well when the page scales the SVG to fit.
 *
 * LAYOUT FUNCTIONS (one per orientation, see ARCHITECTURE.md §3)
 *   planLayoutStraight(g)     'straight'  flight 1 + top landing
 *   planLayoutInline(g)       'inline'    flight 1, landing, flight 2 straight on
 *   planLayoutL(g)            'L'         flight 2 turned 90 degrees to the right
 *   planLayoutU(g)            'U'         flight 2 returns 180 degrees on the right
 *   planLayoutUpper(g, fs)    the upper landing view (drawing 2), any orientation
 *   The direction is fixed (L turns right, U returns on the right); old saved
 *   values 'L-left' / 'L-right' / 'U-left' / 'U-right' are mapped to 'L' / 'U'
 *   by planNormalizeOrientation.
 *   Each returns a small "model" (flights, landing, which side gets the
 *   dimensions and which side gets the labels). Everything after that
 *   (drawing steel, dimensions, labels, title) is shared code.
 *
 * DRAWING ORDER
 *   planRender (drawing 1):
 *     paper -> landing fill -> treads -> flight outlines -> deck symbol ->
 *     landing X beams -> landing Y beams -> stringers -> UP arrows ->
 *     dimensions -> labels -> title + axis key
 *   planRenderUpper (drawing 2):
 *     paper -> landing fill -> stub treads -> deck symbol + landing beams ->
 *     stringers -> break line + stringer break marks -> UP arrow ->
 *     width / depth dimensions -> tread note -> labels -> title + axis key
 *
 * HOW TO EDIT
 *   - Colours: do not edit this file. Change the --plan-* tokens in
 *     css/styles.css (light and dark blocks). The values after the commas in
 *     PLAN_CSS below are only fallbacks for when the SVG is used on its own.
 *       --plan-paper    sheet background
 *       --plan-ink      outlines, leaders, text, break lines
 *       --plan-muted    tread lines, hatch, axis key arrows
 *       --plan-steel    stringers and landing X / Y beams (bold)
 *       --plan-dim      dimension lines, ticks and dimension text
 *       --plan-landing  landing fill
 *   - Label wording: edit PLAN_TEXT just below. {SECTION} is replaced with the
 *     chosen channel size, "\n" starts a new line. PLAN_TEXT.beam is used for
 *     both the X and the Y landing beam labels; PLAN_TEXT.axisX / axisY are
 *     the letters on the axis key; PLAN_TEXT.title / upperTitle (and detail /
 *     upperDetail, the drawing numbers) are the two drawing titles.
 *   - Stringer position: PLAN_STRINGER_INSET (in from the flight edge) and
 *     PLAN_INNER_GAP (centre-to-centre of the two inner stringers).
 *   - Landing beam position: PLAN_BEAM_EDGE_INSET (first / last beam in from
 *     the landing edges; the same rule for X and Y, see planBeamPositions).
 *   - Upper landing view: PLAN_UPPER_TREADS (treads shown on the arriving
 *     flight), PLAN_UPPER_TAIL_D / _FS (cut-off length past the last shown
 *     nosing) and PLAN_BREAK_* (break line and stringer break mark sizes).
 *   - Text size / line weights: the PLAN_*_U and PLAN_TEXT_* constants.
 *   - Label clearance: every piece of text is recorded in ctx.obstacles as it
 *     is drawn, and leader labels slide along their column to avoid covering
 *     or crossing it (planPlaceLabels). Tune with PLAN_OBSTACLE_PAD and
 *     PLAN_LABEL_TRIES.
 *   - Add an orientation: write a planLayoutXxx(g) that returns the same model
 *     shape as the others (copy planLayoutL as a template), add it to
 *     planLayout(), add a branch to planLayoutUpper(), add the name to
 *     PLAN_ORIENTATIONS (and to the fallback in planNormalizeOrientation),
 *     and add the <option> in index.html plus normalizeOrientation(),
 *     landingWidth() and the flight count in calc.js.
 *
 * NAMING
 *   All scripts on the page share one global scope, so every top-level name in
 *   this file starts with "PLAN_" or "plan" (except renderPlan and
 *   renderUpperLanding) to avoid clashing with calc.js and app.js.
 * ========================================================================== */

