/**
 * Clear `svgEl` and draw the stair framing plan for `state`
 * ("1 | STAIR FRAMING PLAN").
 * Safe to call on every input event; it never throws.
 *
 * @param {SVGSVGElement} svgEl  the <svg id="plan"> element
 * @param {object} state         the shared state object (ARCHITECTURE.md §1)
 */
function renderPlan(svgEl, state) {
  if (!svgEl || typeof svgEl.appendChild !== 'function') return;
  try {
    planRender(svgEl, state || {});
  } catch (err) {
    // A drawing bug must never break the budget tool: show a note instead.
    try {
      if (typeof console !== 'undefined') console.warn('renderPlan:', err);
      planRenderError(svgEl);
    } catch (e) { /* give up quietly */ }
  }
}

/**
 * Clear `svgEl` and draw the upper landing view for `state`
 * ("2 | UPPER LANDING FRAMING PLAN", ARCHITECTURE.md §3 "Upper landing"):
 * the landing at the top of the last flight (flight 1 for 'straight',
 * otherwise flight 2), the same size as landing 1 with the same X / Y beams,
 * labels, deck symbol and width / depth dimensions, plus the last 3 treads of
 * the arriving flight with its stringers and UP arrow, cut off with a zig-zag
 * break line. Placement: straight / inline = landing above the flight;
 * L = landing to the right of flight 2; U = full-width landing below
 * flight 2, which meets the right half of its top edge.
 *
 * Text is sized from the MAIN stair's overall size, so it matches drawing 1
 * when both are shown at the same scale.
 *
 * When landingCount (clamped) is less than 2 the svg is emptied, given a
 * zero viewBox ("0 0 0 0", which renders nothing) and left like that.
 * Safe to call on every input event; it never throws (a drawing bug shows a
 * short note instead).
 *
 * @param {SVGSVGElement} svgEl  the <svg id="planUpper"> element
 * @param {object} state         the shared state object (ARCHITECTURE.md §1)
 */
function renderUpperLanding(svgEl, state) {
  if (!svgEl || typeof svgEl.appendChild !== 'function') return;
  try {
    planRenderUpper(svgEl, state || {});
  } catch (err) {
    try {
      if (typeof console !== 'undefined') console.warn('renderUpperLanding:', err);
      planRenderError(svgEl);
    } catch (e) { /* give up quietly */ }
  }
}

/* =============================================================================
 * Main pipelines
 * ========================================================================== */

/**
 * Does the real work for renderPlan(): normalise input, lay out, draw, fit.
 *
 * @param {SVGSVGElement} svgEl
 * @param {object} state
 */
function planRender(svgEl, state) {
  const g = planReadState(state);          // clamped numbers + label strings
  const model = planLayout(g);              // flights + landing positions (in)

  // Size of the stair itself drives the unit, text size and line weights.
  const gb = planGeomBounds(model, g);
  const ctx = planNewCtx(svgEl, g, planUnit(gb));
  const paper = planBegin(ctx, 'Stair framing plan, ' + g.orientation);

  // --- the stair itself -----------------------------------------------------
  if (model.landing) planDrawLandingFill(ctx, model.landing);
  model.flights.forEach(function (f) { planDrawTreads(ctx, f); });
  if (model.landing) planDrawLandingSteel(ctx, model.landing, model.chainSide);
  model.flights.forEach(function (f) { planDrawStringers(ctx, f); });
  model.flights.forEach(function (f) { planDrawUpArrow(ctx, f); });

  // --- annotation -----------------------------------------------------------
  planDrawDimensions(ctx, model, gb);
  planPlaceLabels(ctx);
  const tb = planDrawTitle(ctx, gb);
  if (model.landing && (g.nBeamsX > 0 || g.nBeamsY > 0)) planDrawAxisKey(ctx, tb);

  planFinish(svgEl, ctx, paper, 'Stair framing plan: ' + g.orientation + ', ' +
    g.treads1 + (g.hasFlight2 ? ' + ' + g.treads2 : '') + ' treads');
}

/**
 * Does the real work for renderUpperLanding(): normalise input, size the
 * text from the MAIN stair, lay out the upper landing, draw, fit.
 *
 * @param {SVGSVGElement} svgEl
 * @param {object} state
 */
function planRenderUpper(svgEl, state) {
  const g = planReadState(state);
  if (g.nLandings < 2) {
    // Only one landing: nothing to show (app.js also hides the wrapper).
    planClear(svgEl);
    svgEl.setAttribute('viewBox', '0 0 0 0');
    svgEl.removeAttribute('aria-label');
    return;
  }

  // Text and line weights from the main drawing's stair, not this small view.
  const ctx = planNewCtx(svgEl, g, planUnit(planGeomBounds(planLayout(g), g)));
  const model = planLayoutUpper(g, ctx.fs);
  const gb = planGeomBounds(model, g);
  const paper = planBegin(ctx, 'Upper landing framing plan, ' + g.orientation);
  const ld = model.landing, f = model.flights[0];

  // --- the landing and the arriving flight stub -----------------------------
  if (ld) planDrawLandingFill(ctx, ld);
  if (f) planDrawStubTreads(ctx, f);
  if (ld) planDrawLandingSteel(ctx, ld, model.depthSide);
  if (f) {
    planDrawStringers(ctx, f);
    planDrawBreak(ctx, f);
    planDrawUpArrow(ctx, f);
  }

  // --- annotation -----------------------------------------------------------
  planDrawUpperDimensions(ctx, model, gb);
  if (f) planDrawStubNote(ctx, f, model.arriving);
  planPlaceLabels(ctx);
  const tb = planDrawTitle(ctx, gb, PLAN_TEXT.upperDetail, PLAN_TEXT.upperTitle);
  if (ld && (g.nBeamsX > 0 || g.nBeamsY > 0)) planDrawAxisKey(ctx, tb);

  planFinish(svgEl, ctx, paper, 'Upper landing framing plan: ' + g.orientation +
    ', top of flight ' + model.arriving.num);
}

/**
 * Drawing unit for a stair with bounds `gb`: (largest stair dimension) x
 * PLAN_UNIT_RATIO, clamped. Text sizes and line weights are multiples of it.
 *
 * @param {{x0:number,y0:number,x1:number,y1:number}} gb  stair bounds (in)
 * @returns {number} u (in)
 */
function planUnit(gb) {
  const size = Math.max(gb.x1 - gb.x0, gb.y1 - gb.y0, 24);
  return planClamp(size * PLAN_UNIT_RATIO, PLAN_UNIT_MIN, PLAN_UNIT_MAX);
}

/**
 * Fresh drawing context: the off-DOM fragment everything is built in, the
 * unit and font size, the drawn extents, queued labels and text obstacles.
 *
 * @param {SVGSVGElement} svgEl
 * @param {object} g   from planReadState
 * @param {number} u   drawing unit (planUnit)
 * @returns {object} ctx
 */
function planNewCtx(svgEl, g, u) {
  const doc = svgEl.ownerDocument || document;
  return {
    doc: doc,
    root: doc.createDocumentFragment(),     // build off-DOM, attach once
    u: u,
    fs: u * PLAN_FONT_U,                    // font size in inches
    ext: { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity },
    labels: [],                             // leader labels, placed at the end
    obstacles: [],                          // text boxes labels must steer around
    g: g,
  };
}

/**
 * First elements of every drawing: the <style>, a <title> and the paper rect
 * (sized at the very end by planFinish).
 *
 * @param {object} ctx
 * @param {string} title  accessible title text
 * @returns {SVGRectElement} the paper rect
 */
function planBegin(ctx, title) {
  planEl(ctx, 'style', {}, PLAN_CSS);
  planEl(ctx, 'title', {}, title);
  return planEl(ctx, 'rect', { class: 'sp-paper', fill: '#ffffff' });
}

/**
 * Fit the viewBox around everything drawn (plus a margin), size the paper
 * and swap the new drawing into the svg.
 *
 * @param {SVGSVGElement} svgEl
 * @param {object} ctx
 * @param {SVGRectElement} paper  from planBegin
 * @param {string} aria           aria-label for the svg
 */
function planFinish(svgEl, ctx, paper, aria) {
  const m = ctx.fs * PLAN_MARGIN;
  const e = ctx.ext;
  const vb = [e.x0 - m, e.y0 - m, (e.x1 - e.x0) + 2 * m, (e.y1 - e.y0) + 2 * m].map(planR);
  planSetAttrs(paper, { x: vb[0], y: vb[1], width: vb[2], height: vb[3] });

  planClear(svgEl);
  svgEl.setAttribute('viewBox', vb.join(' '));
  svgEl.setAttribute('preserveAspectRatio', 'xMidYMid meet');
  svgEl.setAttribute('role', 'img');
  svgEl.setAttribute('aria-label', aria);
  svgEl.appendChild(ctx.root);
}

/**
 * Remove every child of the svg.
 *
 * @param {SVGSVGElement} svgEl
 */
function planClear(svgEl) {
  while (svgEl.firstChild) svgEl.removeChild(svgEl.firstChild);
}

/**
 * Fallback drawing when something went wrong: a short note on the sheet.
 *
 * @param {SVGSVGElement} svgEl
 */
function planRenderError(svgEl) {
  planClear(svgEl);
  svgEl.setAttribute('viewBox', '0 0 200 60');
  const t = (svgEl.ownerDocument || document).createElementNS(PLAN_SVG_NS, 'text');
  planSetAttrs(t, { x: 100, y: 34, 'text-anchor': 'middle', 'font-size': 8, fill: '#767676',
    'font-family': PLAN_FONT });
  t.textContent = 'PLAN VIEW UNAVAILABLE FOR THESE INPUTS';
  svgEl.appendChild(t);
}

