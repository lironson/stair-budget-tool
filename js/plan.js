/**
 * Point on a flight in flight coordinates.
 *   s = distance along the direction of travel from the flight's START (the
 *       lower end of the stair), 0..run (may go past either end for jogs)
 *   t = distance across the flight from its x0 (vertical) / y0 (horizontal)
 *       edge, 0..width
 *
 * @param {object} f
 * @param {number} s
 * @param {number} t
 * @returns {{x:number,y:number}}
 */
function planFP(f, s, t) {
  switch (f.dir) {
    case 'up': return { x: f.x0 + t, y: f.y1 - s };
    case 'down': return { x: f.x0 + t, y: f.y0 + s };
    case 'left': return { x: f.x1 - s, y: f.y0 + t };
    default: return { x: f.x0 + s, y: f.y0 + t };       // 'right'
  }
}

/**
 * True when the flight runs up or down the screen.
 *
 * @param {object} f
 * @returns {boolean}
 */
function planIsVertical(f) {
  return f.dir === 'up' || f.dir === 'down';
}

/**
 * Across-positions (t) of the stringers on a flight.
 *
 * @param {object} ctx
 * @param {object} f
 * @returns {{outer:number[], inner:number[]}}
 */
function planStringerPositions(ctx, f) {
  const W = f.width;
  // Keep the stroke inside the flight edge, and never more than W/6 in.
  const inset = Math.min(Math.max(PLAN_STRINGER_INSET, ctx.u * PLAN_STEEL_U * 0.6), W / 6);
  const gap = Math.min(PLAN_INNER_GAP, W / 5);
  const inner = ctx.g.nStringers >= 4 ? [W / 2 - gap / 2, W / 2 + gap / 2]
    : ctx.g.nStringers === 3 ? [W / 2] : [];
  return { outer: [inset, W - inset], inner: inner };
}

